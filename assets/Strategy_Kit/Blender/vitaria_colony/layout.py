def plot_flat(x, y):
    """1 на поле и полосе 0.9 м вокруг, дальше плавный спад в лёгкие холмы."""
    return 1.0 - T.smoothstep(0.9, 2.2, P.dist_to_plot(x, y))


def plot_calm(x, y):
    """Крупные пятна рампы на поле чуть тише, чем вокруг (сверху их всё равно перекрывают lawn_patches)."""
    return 0.25 * (1.0 - T.smoothstep(0.2, 1.6, P.dist_to_plot(x, y)))


BORDER = (0.1, 0.35, -0.5)      # межа: от, до (м за краем поля), сдвиг по рампе в середине полосы


def lawn_patches(x, y):
    """Пятна поляны: тёмные куртины клевера и светлые вытоптанные места (3–5 м), плюс межа по краю
    поля. Без пятен поле читалось как ровный салатовый газон — самое пустое место кадра."""
    from mathutils import Vector, noise
    n1 = noise.noise(Vector((x * 0.27 + 3.1, y * 0.27 - 7.7, 1.9)))
    n2 = noise.noise(Vector((x * 0.61 - 2.3, y * 0.61 + 5.2, 4.4)))
    k = n1 + 0.35 * n2
    dt = -0.38 * T.smoothstep(0.08, 0.4, k) + 0.2 * T.smoothstep(0.14, 0.44, -k)
    d = P.dist_to_plot(x, y)
    if d > 0.0:
        a, b, depth = BORDER
        mid = (a + b) / 2
        band = T.smoothstep(0.0, a, d) * (1.0 - T.smoothstep(mid, b, d))
        dt = dt * (1.0 - band) + depth * band
    return dt


def border_points(step=0.33):
    """Ряды вершин травы вдоль края поля (снаружи): без них межа 0.25 м размазалась бы сеткой 0.72 м."""
    pts = []
    for off in (0.0, 0.1, 0.22, 0.35, 0.5):
        hw, hh = P.HALF_W + off, P.HALF_H + off
        for (x0, y0), (x1, y1) in (((-hw, -hh), (hw, -hh)), ((hw, -hh), (hw, hh)), ((hw, hh), (-hw, hh)),
                                   ((-hw, hh), (-hw, -hh))):
            L = ((x1 - x0) ** 2 + (y1 - y0) ** 2) ** 0.5
            n = max(1, int(round(L / step)))
            for k in range(n):
                t = k / n
                pts.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t))
    return pts


