def plot_flat(x, y):
    """1 на поле и полосе 0.9 м вокруг, дальше плавный спад в лёгкие холмы."""
    return 1.0 - T.smoothstep(0.9, 2.2, P.dist_to_plot(x, y))


def plot_calm(x, y):
    """Цвет травы на поле ровнее, чем вокруг: пятна приглушены, но не стёрты."""
    return 0.55 * (1.0 - T.smoothstep(0.2, 1.6, P.dist_to_plot(x, y)))


