"""
Склад экипировки: запертый каменный склад под синей кровлей. Главный приём — крупный
геральдический щит со скрещёнными мечами на деревянном фронтоне прямо над окованной
дверью, которую перечёркивает брус-засов с золотым замком: с игровой дистанции читается
«здесь хранят оружие, и оно под замком». Огня и трубы нет — в отличие от кузницы,
здание глухое: решётки на окнах, стойки с оружием и манекен снаружи у входа.
"""
import math
from build_vitaria import p_box, p_cyl, p_prism, p_taper_box, by_normal
from vitaria_buildings.common import (Frame, gable_roof, gable_wall, stone_base, cornice, banner,
                                      barrel, heater_shield, spear, sword, armor_stand,
                                      STONE_DARK_TOP)

NAME = "Bld_Armory"
TITLE = "Склад экипировки"
TARGET = (4.2, 3.4, 3.9)   # w, d, h в метрах

W, D = 3.2, 2.4            # каменная коробка
F = 0.28                   # верх цоколя = пол склада
ZT = 2.25                  # верх каменных стен
PITCH = 39.0
YF = -D / 2                # фасад смотрит в -Y
DW, DH = 1.36, 1.32        # проём двери
ZB = F + DH * 0.52         # ось бруса-засова
YS, ZS = -1.38, 2.53       # рама щита: тыл кромки на 1 см перед брусом обвязки


def _quoins(a):
    """Угловые русты: блоки через ряд длинной стороной на фасад и на бок, выступ 6 см."""
    n, p = 4, 0.06
    hq = (ZT - F) / n
    for sx in (-1, 1):
        for sy in (-1, 1):
            for i in range(n):
                lx, ly = (0.50, 0.30) if i % 2 == 0 else (0.30, 0.50)
                # нижний ряд утоплен в цоколь: иначе русты висят над ним на зазоре шва
                z0 = F + i * hq + (0.018 if i else -0.02)
                z1 = F + (i + 1) * hq - 0.018
                a.add(p_box((lx, ly, z1 - z0),
                            loc=(sx * (W / 2 + p - lx / 2), sy * (D / 2 + p - ly / 2), (z0 + z1) / 2),
                            bevel=0.04), "stone_light")


def _barred_window(a, fr, w=0.50, h=0.56):
    """Окно-решётка: чёрная плита в выступающем обрамлении и три толстых прута.
    Рама fr стоит на плоскости стены, локальный -Y смотрит наружу."""
    fr.box(a, (w + 0.02, 0.05, h + 0.02), (0, -0.015, 0), col="black", bevel=0.0)
    for sx in (-1, 1):
        fr.box(a, (0.15, 0.18, h + 0.30), (sx * (w / 2 + 0.075), -0.05, 0), col="stone_light", bevel=0.035)
    fr.box(a, (w + 0.36, 0.20, 0.16), (0, -0.06, h / 2 + 0.08), col="stone_light", bevel=0.04)
    fr.box(a, (w + 0.40, 0.24, 0.12), (0, -0.07, -h / 2 - 0.06), col="stone_light", bevel=0.035)
    # прутья шестигранные: брусок с фаской стоит втрое дороже по треугольникам
    for x in (-w / 3, 0.0, w / 3):
        fr.cyl(a, 0.036, 0.036, h + 0.04, 6, loc=(x, -0.07, -h / 2 - 0.02), col="iron_dark")


def _padlock(a, fr):
    """Навесной замок лицом к -Y: золотой корпус (верх в z=0) и стальная дужка-подкова."""
    fr.box(a, (0.30, 0.13, 0.26), (0, 0, -0.13), col=by_normal("gold_light", "gold", "gold_dark", 0.7),
           bevel=0.035)
    fr.box(a, (0.05, 0.02, 0.09), (0, -0.071, -0.14), col="black", bevel=0.0)      # скважина
    ro, ri, zc, zb, n = 0.11, 0.058, 0.07, -0.03, 5
    pts = [(ro, zb)]
    pts += [(ro * math.cos(math.pi * i / n), zc + ro * math.sin(math.pi * i / n)) for i in range(n + 1)]
    pts += [(-ro, zb), (-ri, zb)]
    pts += [(ri * math.cos(math.pi * (n - i) / n), zc + ri * math.sin(math.pi * (n - i) / n)) for i in range(n + 1)]
    pts += [(ri, zb)]
    fr.prism(a, pts, 0.045, loc=(0, 0, 0), col="iron_light")


def _door(a):
    """Окованная двустворчатая дверь в каменном портале, брус в скобах и замок по центру."""
    z0 = F
    # чёрная подложка: щель между створками читается как дверь, а не как стена
    a.add(p_box((DW, 0.04, DH), loc=(0, YF - 0.005, z0 + DH / 2), bevel=0.0), "black")
    for sx in (-1, 1):
        a.add(p_box((DW / 2 - 0.03, 0.12, DH - 0.01), loc=(sx * DW / 4, YF - 0.05, z0 + DH / 2),
                    bevel=0.03), "wood_mid")
        for z in (z0 + 0.22, z0 + DH - 0.22):
            a.add(p_box((DW / 2 - 0.09, 0.06, 0.12), loc=(sx * DW / 4, YF - 0.12, z), bevel=0.02),
                  "iron_dark")
        # косяки портала выступают на 8 см дальше створок — дверь сидит в глубине
        a.add(p_box((0.24, 0.28, DH + 0.02), loc=(sx * (DW / 2 + 0.12), YF - 0.05, z0 + DH / 2),
                    bevel=0.04), "stone_light")
        # скобы засова на косяках: брус проходит сквозь них, поэтому читается как задвинутый
        a.add(p_box((0.10, 0.22, 0.27), loc=(sx * (DW / 2 + 0.13), YF - 0.27, ZB), bevel=0.02),
              "iron_dark")
    a.add(p_box((DW + 0.64, 0.30, 0.24), loc=(0, YF - 0.05, z0 + DH + 0.12), bevel=0.045), "stone_light")
    a.add(p_taper_box((0.22, 0.36), (0.32, 0.36), 0.30, loc=(0, YF - 0.06, z0 + DH - 0.03), bevel=0.03),
          "stone_mid")
    # брус-засов: светлое дерево поперёк тёмных створок — главный знак «заперто»
    a.add(p_box((DW + 0.42, 0.14, 0.16), loc=(0, YF - 0.27, ZB), bevel=0.035),
          by_normal("wood_pale", "wood_light", "wood_mid", 0.7))
    _padlock(a, Frame((0, YF - 0.41, ZB + 0.03)))
    # ступень: пол на 28 см выше земли
    a.add(p_box((DW + 0.80, 0.46, 0.20), loc=(0, YF - 0.34, 0.06), bevel=0.045),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))


def _halberd(a, fr, L=2.1):
    """Алебарда: древко с пятки z=0, топор-полумесяц к +X, клюв к -X, пика сверху."""
    fr.cyl(a, 0.036, 0.03, L - 0.28, 6, col="wood_dark")
    zc = L - 0.42
    fr.cyl(a, 0.05, 0.05, 0.30, 6, loc=(0, 0, zc - 0.15), col="iron_dark")
    # лезвие темнее стали мечей: белая пластина такого размера читалась флажком
    fr.prism(a, [(0.03, -0.10), (0.15, -0.20), (0.27, -0.14), (0.31, 0.03), (0.26, 0.20), (0.03, 0.11)],
             0.045, loc=(0, 0, zc), col="iron_light")
    fr.prism(a, [(-0.03, -0.02), (-0.18, -0.09), (-0.03, 0.08)], 0.04, loc=(0, 0, zc), col="iron")
    fr.taper(a, (0.09, 0.04), (0.01, 0.01), 0.28, loc=(0, 0, L - 0.30), col="steel")


def _weapon_rack(a, fr):
    """Стойка под древковое: два столба, верхняя жердь, лоток под пятки.
    Копья и алебарды стоят в лотке и опираются на лицо жерди — ничего не висит."""
    for sx in (-1, 1):
        fr.box(a, (0.13, 0.13, 1.16), (sx * 0.38, 0, 0.58), col="wood_dark", bevel=0.03)
        fr.cyl(a, 0.10, 0.0, 0.12, 4, loc=(sx * 0.38, 0, 1.16), spin=45, col="gold")
    zr = 1.02
    fr.box(a, (0.90, 0.11, 0.13), (0, 0, zr), col="wood_mid", bevel=0.03)
    fr.box(a, (0.86, 0.30, 0.13), (0, -0.14, 0.10), col=by_normal("wood_light", "wood_mid", "wood_dark", 0.7),
           bevel=0.03)
    lean = 6.0
    zb = 0.12
    for x, kind, L, side in ((-0.27, "spear", 1.95, -2), (-0.09, "halberd", 2.12, 1),
                             (0.09, "spear", 2.02, -1), (0.27, "halberd", 2.05, 2)):
        yb = -0.055 - 0.036 - (zr - zb) * math.tan(math.radians(lean))
        s = fr.sub((x, yb, zb), rot=(-lean, side, 0))
        if kind == "spear":
            spear(a, s, L=L)
        else:
            _halberd(a, s, L=L)


def _sword_barrel(a, fr):
    """Открытая бочка с мечами рукоятями вверх; чёрный круг сверху — пустое нутро."""
    barrel(a, tuple(fr.at((0, 0, 0))), r=0.22, h=0.50)
    fr.cyl(a, 0.19, 0.19, 0.02, 10, loc=(0, 0, 0.495), col="black")
    # два меча крест-накрест — эхо эмблемы на щите. rot Y=180 переворачивает меч остриём
    # вниз; остриё на дне, над краем ~0.35 м клинка: одни рукояти читались цветами в кадке
    for dx, ty in ((-0.07, -13), (0.07, 13)):
        sword(a, fr.sub((dx, -0.02, 1.12), rot=(0, 180 + ty, 0)), L=1.10)


def build(a):
    # --- цоколь и каменная коробка
    stone_base(a, W + 0.28, D + 0.28, h=F, col=STONE_DARK_TOP)
    a.add(p_box((W, D, ZT - F + 0.02), loc=(0, 0, (F + ZT) / 2 - 0.01), bevel=0.05), "stone_mid")
    _quoins(a)
    cornice(a, W, D, ZT, t=0.18, col="wood_dark")

    # --- кровля и деревянные фронтоны: тёплое дерево держит синий щит лучше серого камня
    # свес по торцам всего 8 см: при обычных 22 см причелины заслоняли верх щита
    # от игровой камеры, а так щит поднимается под самый скат
    zr = gable_roof(a, W, D, ZT, pitch_deg=PITCH, ox=0.28, oy=0.08)
    gable_wall(a, W, ZT - 0.02, zr, D, col="wood_mid", inset=0.05, depth=0.14)

    # --- герой: геральдический щит 1.0 x 1.18 м на фронтоне. Углы кромки на 2 см ниже
    # причелин, остриё на 6 см выше замкового камня портала
    heater_shield(a, Frame((0, YS, ZS)), w=0.88, h=1.06, t=0.07, face="roof", rim="gold",
                  emblem="swords", paint="steel")
    # опорный брус за щитом: щит вынесен перед обвязкой и без него висел бы в воздухе
    a.add(p_box((0.24, 0.13, 0.24), loc=(0, YF - 0.085, ZS + 0.12), bevel=0.0), "wood_dark")

    _door(a)

    # --- хоругви по сторонам портала: перекладина упирается в низ бруса обвязки
    # (низ бруса 2.16), так полотно подвешено к нему без отдельных крюков
    # золотой шеврон нужен, чтобы узкое синее полотно не читалось ставнем
    chev = [(-0.12, -0.07), (0.0, 0.04), (0.12, -0.07), (0.12, 0.04), (0.0, 0.15), (-0.12, 0.04)]
    for sx in (-1, 1):
        banner(a, (sx * 1.08, YF - 0.10, 2.062), w=0.28, h=0.80, col="roof", pole=False)
        a.add(p_prism(chev, 0.02, loc=(sx * 1.08, YF - 0.13, 1.70)), "gold")

    # --- слева стойка с копьями и алебардами, справа манекен в доспехе и бочка мечей.
    # Стойка вынесена наружу за хоругвь: в фас её копья не перечёркивают полотно
    _weapon_rack(a, Frame((-1.70, -1.58, 0)))
    armor_stand(a, Frame((1.36, -1.66, 0), rz=8))
    _sword_barrel(a, Frame((1.90, -1.62, 0)))

    # --- решётки на боках; тыл глухой — склад и должен быть глухим, русты его держат
    for sx in (-1, 1):
        _barred_window(a, Frame((sx * W / 2, 0.20, 1.34), rz=sx * 90))
