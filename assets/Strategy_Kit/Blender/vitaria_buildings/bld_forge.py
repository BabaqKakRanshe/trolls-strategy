RW, RD = 3.30, 2.30    # коробка под кровлей
HX = -0.95            # ось горна по X
HY0, HY1 = -0.22, 0.925  # горн по Y: вынесен вперёд — жар должен быть виден из-под фасадного прогона

WALL = by_normal("stone_light", "stone_mid", "stone_dark", 0.8)
STEEL = by_normal("steel", "iron", "iron_dark", 0.8)


def _bellows(a, fr, floor_z, rz, L=0.62, w=0.42, h=0.28):
    """Мехи «грушей»: носик в начале рамы смотрит в -X, тело и рукояти уходят в +X, ось — z=0 рамы.
    Доски раскрыты симметрично, поэтому кожаный клин — один p_taper_box; ножки считаются
    в мировых осях, чтобы стоять отвесно и при наклонённой раме."""
    lx0 = 0.12
    ln = L - 0.08 - lx0
    h0, w0 = 0.07, 0.15
    fr.taper(a, (h0, w0), (h, w * 0.84), ln, loc=(lx0, 0, 0), rot=(0, 90, 0), col="leather", bevel=0.015)
    for t in (0.40, 0.78):
        fr.box(a, (0.045, w0 + (w * 0.84 - w0) * t + 0.03, h0 + (h - h0) * t + 0.03),
               (lx0 + ln * t, 0, 0), col="leather_dark", bevel=0.012)
    th = math.atan2((h - h0) / 2, ln)
    blen = ln / math.cos(th) + 0.10
    outline = [(0.0, -0.065), (0.28 * blen, -0.12), (0.62 * blen, -w / 2), (0.9 * blen, -w * 0.45),
               (blen, -w * 0.28), (blen, w * 0.28), (0.9 * blen, w * 0.45), (0.62 * blen, w / 2),
               (0.28 * blen, 0.12), (0.0, 0.065)]
    for sz in (1, -1):
        bd = fr.sub((lx0 - 0.04, 0, sz * h0 / 2), rot=(0, -sz * math.degrees(th), 0))
        bd.prism(a, outline, 0.05, loc=(0, 0, sz * 0.025), rot=(90, 0, 0),
                 col="wood_light" if sz > 0 else "wood_mid")
        bd.box(a, (0.16, 0.08, 0.05), (blen + 0.05, 0, sz * 0.025), col="wood_dark", bevel=0.015)
    fr.cyl(a, 0.042, 0.026, lx0 + 0.02, 8, loc=(lx0 + 0.02, 0, 0), rot=(0, -90, 0), col="iron_dark")
    fr.cyl(a, 0.056, 0.056, 0.05, 8, loc=(lx0 - 0.01, 0, 0), rot=(0, 90, 0), col="copper")
    x = lx0 + ln * 0.72
    zu = -h0 / 2 - (x - lx0 + 0.04) * math.tan(th) - 0.05 + 0.006
    feet = [fr.at((x, sy * w * 0.26, zu)) for sy in (-1, 1)]
    for P in feet:
        hz = P.z - floor_z + 0.01
        a.add(p_box((0.08, 0.08, hz), loc=(P.x, P.y, floor_z - 0.01 + hz / 2), rot=(0, 0, rz), bevel=0.02),
              "wood_dark")
    mid = (feet[0] + feet[1]) / 2
    a.add(p_box((0.06, w * 0.52 + 0.10, 0.07), loc=(mid.x, mid.y, floor_z + 0.14), rot=(0, 0, rz), bevel=0.015),
          "wood_dark")


def _anvil(a, fr):
    """Наковальня-герой ~0.93 м с рогом в +X рамы; низ лапы в z=0, рабочая плоскость на 0.38.
    Верх — светлая сталь: с игровой камеры наковальню узнают по светлой плоскости и рогу."""
    fr.box(a, (0.48, 0.34, 0.08), (0.0, 0, 0.04), col="iron_dark", bevel=0.02)
    fr.taper(a, (0.34, 0.24), (0.22, 0.16), 0.15, loc=(0, 0, 0.075), col="iron_dark")
    fr.box(a, (0.56, 0.30, 0.16), (0.0, 0, 0.30), col=STEEL, bevel=0.025)
    # пятка ступенькой и рог-конус; ось рога ниже рабочей плоскости, как у настоящей
    fr.box(a, (0.12, 0.22, 0.10), (-0.32, 0, 0.32), col=STEEL, bevel=0.02)
    fr.cyl(a, 0.105, 0.015, 0.30, 8, loc=(0.27, 0, 0.27), rot=(0, 90, 0), col="iron")
    fr.box(a, (0.06, 0.06, 0.012), (-0.18, 0.0, 0.381), col="black", bevel=0.0)


def _tongs(a, fr, L=0.56):
    """Клещи на стене: две железные полосы крест-накрест, шарнир у губок.
    Рама: X — вдоль стены, -Y — наружу от стены, низ ручек в z=0."""
    # полосы без фаски: у бруска 5x4 см она не видна, а стоит 32 треугольника
    for s in (-1, 1):
        fr.box(a, (0.05, 0.04, L), (s * 0.035, 0, L / 2), rot=(0, s * 7, 0), col="iron_dark", bevel=0.0)
    fr.box(a, (0.06, 0.05, 0.06), (0, -0.01, L * 0.72), col="iron_light", bevel=0.0)


def _anvil_sign(a, fr, s=1.0):
    """Силуэт наковальни для вывески: вогнутый многоугольник в плоскости XZ, рог вправо."""
    pts = [(-0.11, -0.11), (0.09, -0.11), (0.09, -0.07), (0.04, -0.04), (0.05, 0.0), (0.17, 0.05),
           (0.06, 0.07), (-0.15, 0.07), (-0.15, 0.02), (-0.05, 0.0), (-0.06, -0.04), (-0.11, -0.07)]
    fr.prism(a, [(x * s, z * s) for x, z in pts], 0.024, col="iron_dark")


def _floor(a):
    # ---- цоколь и пол ---------------------------------------------------------------------
    # Пол — отдельная плита со светлым верхом: у открытой мастерской это самая большая видимая
    # грань, на тёмном камне реквизит тонул бы. Перед фасадом — вынос под товар.
    a.add(p_box((3.60, 3.06, 0.30), loc=(0, -0.10, 0.01), bevel=0.06),
          by_normal("stone_mid", "stone_dark", "stone_dark", 0.8))
    a.add(p_box((3.40, 2.86, 0.14), loc=(0, -0.10, F - 0.07), bevel=0.04), STONE_TOP)


def _walls_l1(a):
    # ---- каменные стены: левая и задняя (у огня кладка, а не доски) ------------------------
    hw = ZW - ZB
    a.add(p_box((0.38, 2.55, hw), loc=(-1.56, 0.035, ZB + hw / 2), bevel=0.05), WALL)
    a.add(p_box((3.47, 0.38, hw), loc=(0.015, 1.09, ZB + hw / 2), bevel=0.05), WALL)
    # угловые квадры выступают на 4 см: на игровой дистанции только они держат углы кладки
    for x0, x1, y0, y1 in ((-1.79, -1.33, -1.28, -1.14), (1.65, 1.79, 0.86, 1.32), (-1.79, -1.65, 0.96, 1.35)):
        a.add(p_box((x1 - x0, y1 - y0, hw - 0.02), loc=((x0 + x1) / 2, (y0 + y1) / 2, ZB + (hw - 0.02) / 2),
                    bevel=0.035), "stone_light")
    # щелевые продухи: без них глухая кладка снаружи читалась сараем
    a.add(p_box((0.10, 0.30, 0.64), loc=(-1.76, -0.45, 1.45), bevel=0.025), "stone_light")
    a.add(p_box((0.08, 0.12, 0.48), loc=(-1.80, -0.45, 1.45), bevel=0.0), "black")
    a.add(p_box((0.30, 0.10, 0.64), loc=(0.55, 1.29, 1.45), bevel=0.025), "stone_light")
    a.add(p_box((0.12, 0.08, 0.48), loc=(0.55, 1.33, 1.45), bevel=0.0), "black")
    # Наружная сторона кладки: на листе тыл и левый бок читались гладкой плитой. Тёмный цоколь
    # по низу и россыпь выступающих камней дают масштаб кладки; камни — плоские накладки без
    # фаски (5 см), по 12 треугольников, на 5 мм впереди стены.
    STONE_DARK = by_normal("stone_mid", "stone_dark", "stone_dark", 0.8)
    a.add(p_box((3.30, 0.08, 0.40), loc=(0.0, 1.31, 0.32), bevel=0.02), STONE_DARK)
    a.add(p_box((0.08, 2.08, 0.40), loc=(-1.78, -0.09, 0.32), bevel=0.02), STONE_DARK)
    # (накладные камни на тылу и левом боку сняты: камера колонии смотрит с юга-востока, их не видно)
    # у тыла — поленница под свесом кровли: тёплое пятно и топливо для горна. Поленья торцом
    # наружу (светлые срезы читаются как дрова), лежат на двух лагах прямо на земле за цоколем.
    wp = Frame((0.70, 1.69, 0.0))
    for sy in (-1, 1):
        wp.box(a, (1.00, 0.10, 0.08), (0, sy * 0.16, 0.04), col="wood_dark", bevel=0.02)
    for row, n in enumerate((3, 2)):
        for k in range(n):
            x = (k - (n - 1) / 2) * 0.235
            wp.cyl(a, 0.11, 0.11, 0.50, 7, loc=(x, -0.25, 0.19 + row * 0.19), rot=(-90, 0, 0),
                   col=lambda f: "wood_pale" if abs(f.normal.y) > 0.7 else "bark", bevel=0.015)
    for sx in (-1, 1):
        wp.box(a, (0.08, 0.08, 0.50), (sx * 0.53, 0.0, 0.25), col="wood_dark", bevel=0.02)


def _frame_l1(a):
    # ---- деревянный каркас: стойки правого бока и прогоны по верху --------------------------
    for y in (YF, YM):
        a.add(p_box((0.32, 0.32, 0.10), loc=(PX, y, F + 0.03), bevel=0.03), "stone_dark")
        post(a, PX, y, F + 0.06, ZT - 0.10 - F - 0.06, s=0.20, col="wood_mid")
    a.add(p_box((3.52, 0.22, 0.20), loc=(0.03, YF, ZT - 0.10), bevel=0.04), "wood_dark")
    a.add(p_box((0.22, 2.24, 0.19), loc=(PX, 0.03, ZT - 0.105), bevel=0.04), "wood_dark")
    a.add(p_box((0.30, 2.50, 0.19), loc=(-1.56, 0.02, ZT - 0.105), bevel=0.04), "wood_dark")
    a.add(p_box((3.44, 0.30, 0.19), loc=(0.03, 1.09, ZT - 0.105), bevel=0.04), "wood_dark")
    # раскосы: на фасаде у правой стойки и у каменной стены, на боку — у средней стойки
    brace(a, PX - 0.23, YF, ZT - 0.42, length=0.62, angle=-45)
    brace(a, XL + 0.22, YF, ZT - 0.42, length=0.62, angle=45)
    for sy in (-1, 1):
        brace(a, PX, YM + sy * 0.23, ZT - 0.42, length=0.62, angle=-sy * 45, axis="x")


def _roof_l1(a):
    # ---- кровля и фронтоны -------------------------------------------------------------------
    zr = gable_roof(a, RW, RD, ZT, pitch_deg=30, ox=0.24, oy=0.30)     # свес 0.24: след 2x2 при масштабе 0.5
    # фронтоны на 4 см впереди прогонов: вровень с ними грани фронтона и бруса сливались
    for yc in (YF - 0.01, 1.11):
        a.add(p_prism([(-RW / 2, ZT - 0.02), (RW / 2, ZT - 0.02), (0, zr - 0.04)], 0.28, loc=(0, yc, 0)),
              "wood_light")
    # труба горна выходит сквозь левый скат и поднята над коньком
    chimney(a, HX - 0.03, 0.70, 1.98, h=1.74, w=0.52)


def _hearth(a, zt_hood=ZT):
    rng = random.Random(3)
    # ---- горн: каменный стол, низкий бортик, горка углей, колпак-клин к стене ---------------------
    # Угли лежат выше бортика и ближе к фасаду: на первом рендере горн стоял у задней стены,
    # высокий бортик и фасадный прогон закрывали жар от любой камеры.
    hy = (HY0 + HY1) / 2
    zt = F + 0.60                               # верх стола горна
    a.add(p_box((0.92, HY1 - HY0, zt - F + 0.02), loc=(HX, hy, (F - 0.02 + zt) / 2), bevel=0.04), WALL)
    a.add(p_box((0.98, 0.12, 0.08), loc=(HX - 0.01, HY0 + 0.05, zt + 0.02), bevel=0.025), "stone_light")
    a.add(p_box((0.13, HY1 - HY0 - 0.06, 0.11), loc=(HX + 0.42, hy + 0.03, zt + 0.035), bevel=0.03), "stone_light")
    a.add(p_box((0.74, 0.66, 0.04), loc=(HX - 0.06, 0.16, zt + 0.01), bevel=0.0), "coal")
    for dx, dy, r, col in ((-0.24, 0.02, 0.11, "ember"), (0.02, -0.02, 0.12, "glow"), (0.20, 0.10, 0.10, "ember"),
                           (-0.12, 0.24, 0.11, "glow"), (0.12, 0.30, 0.09, "ember"), (-0.04, 0.12, 0.08, "glow_hot")):
        a.add(p_ico(r, 1, loc=(HX + dx, dy, zt + 0.04), scl=(1.1, 1.0, 0.7), jitter=0.18, rng=rng), col)
    # колпак клином: задняя грань к стене, передняя скошена к трубе; пояс-обрез по низу
    zh, yh = 1.46, HY0 + 0.06
    a.add(p_box((1.10, HY1 - yh + 0.06, 0.10), loc=(HX - 0.03, (yh + HY1) / 2 + 0.01, zh), bevel=0.03), "stone_dark")
    a.add(p_prism([(yh + 0.02, zh + 0.04), (HY1 + 0.05, zh + 0.04), (HY1 + 0.05, zt_hood - 0.18), (0.40, zt_hood - 0.18)],
                  1.02, loc=(HX - 0.03, 0, 0), rot=(0, 0, 90)), WALL)
    # правый передний угол колпака держит каменный столб
    a.add(p_box((0.18, 0.18, zh - zt), loc=(HX + 0.42, HY0 + 0.09, (zh + zt) / 2), bevel=0.03), "stone_light")

    # мехи справа от горна, носик в его бок
    _bellows(a, Frame((HX + 0.44, 0.40, F + 0.40), rot=(0, -6, 0)), floor_z=F, rz=0,
             L=0.64, w=0.42, h=0.28)


def _tool_wall(a):
    # ---- стена с инструментом на левой кладке: видна с герой-ракурса сквозь открытый фасад ------
    a.add(p_box((0.06, 0.74, 0.62), loc=(XL + 0.02, -0.62, 1.36), bevel=0.02), PLANK_TOP)
    for y in (-0.90, -0.32):
        hammer(a, Frame((XL + 0.12, y, 1.02), rz=90), L=0.56)
    _tongs(a, Frame((XL + 0.085, -0.72, 1.04), rz=90), L=0.56)
    _tongs(a, Frame((XL + 0.085, -0.54, 1.08), rz=90), L=0.50)


def _quench_tub(a):
    # ---- кадка для закалки ------------------------------------------------------------------
    # в common.tub венец — сплошной диск и закрывает воду, поэтому зеркало кладём поверх венца:
    # кадка полна до краёв, а тёмное кольцо венца остаётся видно
    tx, ty, tr, th = -0.90, -0.70, 0.34, 0.46
    tub(a, Frame((tx, ty, F - 0.005)), r=tr, h=th, fill="water")
    a.add(p_cyl(tr * 0.9, tr * 0.9, 0.018, 14, loc=(tx, ty, F - 0.005 + th - 0.01)), "water")


def _anvil_group(a, ax=0.10, ay=-0.80):
    # ---- наковальня на пне: у самого фасада, чтобы из-под прогона её видела игровая камера -----
    a.add(p_cyl(0.33, 0.29, 0.46, 8, loc=(ax, ay, F - 0.02), bevel=0.02, spin=10),
          by_normal("wood_pale", "bark", "bark", 0.7))
    a.add(p_cyl(0.32, 0.32, 0.06, 8, loc=(ax, ay, F + 0.26), spin=10), "iron_dark")
    af = Frame((ax, ay, F + 0.435), rz=-8)
    _anvil(a, af)
    # раскалённая заготовка поперёк рабочей плоскости и молот, брошенный рядом
    af.box(a, (0.36, 0.08, 0.03), (0.02, 0.03, 0.39), rot=(0, 0, 14), col="glow", bevel=0.0)
    af.taper(a, (0.03, 0.08), (0.03, 0.01), 0.10, loc=(0.195, 0.074, 0.39), rot=(0, 90, 14), col="glow_hot")
    hf = af.sub((0.12, -0.06, 0.44), rot=(-84, 0, 28))
    hammer(a, hf.sub((0, 0, -0.60)), L=0.62)


def _goods(a):
    # ---- готовый товар: мечи слева, доспех справа ------------------------------------------------
    rk = Frame((-1.08, -1.44, F), rz=6)
    rk.box(a, (1.14, 0.26, 0.10), (0, 0, 0.045), col="wood_dark", bevel=0.025)
    for sx in (-1, 1):
        rk.box(a, (0.09, 0.09, 0.98), (sx * 0.55, 0, 0.49), col="wood_mid", bevel=0.02)
    rk.box(a, (1.20, 0.10, 0.09), (0, 0.02, 0.86), col="wood_mid", bevel=0.02)
    for x, guard in ((-0.36, "gold"), (0.0, "iron_dark"), (0.36, "gold")):
        # меч рукоятью вверх: гарда ложится на жердь, остриё уходит в прорезь основания
        sword(a, rk.sub((x, -0.02, 0.92 + 0.285), rot=(0, 180, 0)), L=1.12, guard=guard)
    # манекен у самого края: на первом рендере он стоял между герой-камерой и наковальней
    armor_stand(a, Frame((1.40, -1.46, F), rz=-20), crest="roof")


def _sign(a, px=PX, yf=YF, zb=2.00):
    # ---- вывеска с силуэтом наковальни на кронштейне правой стойки ----------------------------------
    # консоль короче прежней (0.60): вывеска не выносит здание за след 2x2
    a.add(p_box((0.46, 0.10, 0.10), loc=(px + 0.27, yf, zb), bevel=0.025), "wood_dark")
    # укосина от стойки вверх-наружу под консоль
    a.add(p_box((0.08, 0.08, 0.32), loc=(px + 0.2, yf, zb - 0.15), rot=(0, 48, 0), bevel=0.02), "wood_dark")
    for dx in (0.14, 0.40):
        a.add(p_box((0.05, 0.05, 0.14), loc=(px + dx, yf, zb - 0.11), bevel=0.0), "iron_dark")
    a.add(p_box((0.40, 0.08, 0.32), loc=(px + 0.27, yf, zb - 0.34), bevel=0.03), PLANK_TOP)
    _anvil_sign(a, Frame((px + 0.27, yf - 0.046, zb - 0.34)), s=1.1)


def build(a):
    _floor(a)
    _walls_l1(a)
    _frame_l1(a)
    _roof_l1(a)
    _hearth(a)
    _tool_wall(a)
    _quench_tub(a)
    _anvil_group(a)
    _goods(a)
    _sign(a)


