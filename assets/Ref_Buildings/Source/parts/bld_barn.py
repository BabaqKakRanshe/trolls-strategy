"""
Амбар: каркасный сруб на каменном цоколе, ворота распахнуты наружу.

Открытые створки — главная примета здания, поэтому каменная площадка вынесена
вперёд ровно на глубину их размаха: иначе полотна висят в воздухе над газоном.
Проём вырубить нечем (булевых операций в ките нет), поэтому «дыра» собрана как
чёрная плита чуть впереди стены, обрамлённая выступающими наличниками, — тот же
приём, что в arrow_slit.
"""
import math
from build_vitaria import p_box, p_cyl, p_ico, by_normal
from parts.common import gable_roof, gable_wall, hay_bale, stone_base, post, brace

NAME = "Bld_Barn"
TARGET = (4.6, 3.4, 3.9)   # w, d, h в метрах

W, D, H, F = 3.5, 2.8, 1.63, 0.42   # корпус; верх стен = F + H = 2.05
ZT = F + H
YF = -D / 2                          # фасад смотрит в -Y
DW = 1.70                            # чистая ширина ворот
ZO = F + 1.50                        # верх проёма
OPEN = 55.0                          # раскрытие створок
YH = -1.60                           # линия петель — по передней плоскости наличников
YL = -2.38                           # передний край площадки: створки стоят на камне


def build(a):
    # цоколь и вынесенная вперёд площадка; верхние грани светлее — контраст даёт
    # палитра, а не свет, поэтому по каменным массам идёт by_normal
    stone_base(a, W + 0.34, D + 0.34, h=F,
               col=by_normal("stone_mid", "stone_dark", "stone_dark", 0.8))
    yp = -(D / 2 + 0.17)             # передняя кромка цоколя
    # ширина площадки выбрана по размаху створок плюс место под тюк и вилы
    a.add(p_box((3.30, yp - YL, 0.56), loc=(0, (yp + YL) / 2, 0.14), bevel=0.06),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # бревенчатая масса стен одним объёмом: у кита читается силуэт, а не венцы
    a.add(p_box((W, D, H), loc=(0, 0, F + H / 2), bevel=0.05),
          by_normal("wood_light", "wood_mid", "wood_dark", 0.8))

    zmid = F + H * 0.55
    for sx in (-1, 1):
        for sy in (-1, 1):
            a.add(p_box((0.28, 0.28, H), loc=(sx * W / 2, sy * D / 2, F + H / 2), bevel=0.05),
                  "wood_dark")
        post(a, sx * W / 2, 0.0, F, H, s=0.22)          # средняя стойка боковой стены
        a.add(p_box((0.20, D + 0.10, 0.18), loc=(sx * W / 2, 0, zmid), bevel=0.04), "wood_dark")
        # на фасаде пояс разрезан воротами — иначе брус перечёркивает открытый проём
        a.add(p_box((0.68, 0.20, 0.18), loc=(sx * 1.41, YF, zmid), bevel=0.04), "wood_dark")
        # раскосы держат нижнюю половину боковой стены: каркас читается, а стоит дёшево
        for sy in (-1, 1):
            brace(a, sx * (W / 2 + 0.05), sy * 0.62, (F + zmid) / 2, length=1.10,
                  angle=sy * 40, axis="x")
    a.add(p_box((W + 0.10, 0.20, 0.18), loc=(0, D / 2, zmid), bevel=0.04), "wood_dark")

    zr = gable_roof(a, W, D, ZT, ox=0.38, oy=0.32)
    gable_wall(a, W, ZT, zr, D, col="wood_light")

    # --- проём ворот -------------------------------------------------------------
    for sx in (-1, 1):
        a.add(p_box((0.20, 0.30, 1.50), loc=(sx * (DW / 2 + 0.10), YF - 0.07, F + 0.75),
                    bevel=0.04), "wood_dark")
    a.add(p_box((DW + 0.44, 0.32, 0.20), loc=(0, YF - 0.08, ZO + 0.10), bevel=0.04), "wood_dark")
    # низ плиты утоплен в камень площадки, чтобы не было совпадающих грани в грань
    a.add(p_box((DW + 0.04, 0.12, ZO - 0.30), loc=(0, YF + 0.03, (0.30 + ZO) / 2), bevel=0.0),
          "black")

    # --- створки: петли у наличников, разворот наружу ----------------------------
    ang = math.radians(OPEN)
    for sx in (-1, 1):
        ux, uy = -sx * math.cos(ang), -math.sin(ang)    # от петли к свободному краю
        nx, ny = sx * math.sin(ang), -math.cos(ang)     # наружная сторона полотна
        cx, cy = sx * DW / 2 + ux * 0.425, YH + uy * 0.425
        rz = sx * OPEN
        a.add(p_box((0.85, 0.10, 1.50), loc=(cx, cy, 1.15), rot=(0, 0, rz), bevel=0.03),
              "wood_light")
        for z in (0.64, 1.62):
            a.add(p_box((0.80, 0.08, 0.13), loc=(cx + nx * 0.09, cy + ny * 0.09, z),
                        rot=(0, 0, rz), bevel=0.02), "wood_dark")
        # раскос полотна: наклон задаём по Y до поворота по Z, тогда он лежит в плоскости створки
        a.add(p_box((0.12, 0.08, 1.20), loc=(cx + nx * 0.085, cy + ny * 0.085, 1.15),
                    rot=(0, sx * 24, rz), bevel=0.02), "wood_dark")
        a.add(p_box((0.09, 0.09, 0.20), loc=(cx + ux * 0.34 + nx * 0.10,
                                            cy + uy * 0.34 + ny * 0.10, 1.12),
                    rot=(0, 0, rz), bevel=0.02), "iron_dark")

    # --- нутро проёма: сено видно только впереди чёрной плиты, за ней глухая стена.
    # Стопка сдвинута к оси: при раскрытии 55 град створки закрывают края проёма.
    hay_bale(a, (-0.16, -1.45, F), s=(0.48, 0.32, 0.30))
    hay_bale(a, (-0.10, -1.47, F + 0.30), s=(0.44, 0.30, 0.28), rot=(0, 0, -9))
    for x, y, rz in ((-0.02, -1.54, 18), (0.32, -1.46, -24), (0.18, -2.00, 12)):
        a.add(p_box((0.36, 0.15, 0.07), loc=(x, y, F + 0.035), rot=(0, 0, rz), bevel=0.015),
              "wood_yellow")

    # --- слева от ворот: тюк и вилы ---------------------------------------------
    # тюк вынесен вперёд и влево: иначе угол попадает в сектор, который заметает створка
    hay_bale(a, (-1.30, -2.06, F), s=(0.52, 0.40, 0.34), rot=(0, 0, -14))
    fb = (-1.42, -1.72, F)          # пятка на площадке
    ft = (-1.50, -1.52, 1.46)       # черенок ложится на поясной брус, а не втыкается в кровлю
    dv = [t - b for t, b in zip(ft, fb)]
    fl = math.sqrt(sum(c * c for c in dv))
    ax = [c / fl for c in dv]
    frx = math.degrees(math.asin(-ax[1]))
    fry = math.degrees(math.asin(ax[0] / math.cos(math.radians(frx))))
    a.add(p_cyl(0.035, 0.035, fl, 6, loc=fb, rot=(frx, fry, 0)), "wood_dark")
    # поперечина в основании рожков: без неё два прутка читаются как вторая жердь
    a.add(p_box((0.21, 0.07, 0.07), loc=(ft[0] + ax[0] * 0.05, ft[1] + ax[1] * 0.05,
                                         ft[2] + ax[2] * 0.05),
                rot=(frx, fry, 0), bevel=0.015), "wood_dark")
    for sx in (-1, 1):
        a.add(p_box((0.06, 0.06, 0.22),
                    loc=(ft[0] + ax[0] * 0.16 + sx * 0.075,
                         ft[1] + ax[1] * 0.16, ft[2] + ax[2] * 0.16),
                    rot=(frx, fry, 0), bevel=0.012), "wood_dark")

    # --- справа от ворот: кронштейн и окорок ------------------------------------
    a.add(p_box((0.10, 0.44, 0.10), loc=(1.30, YF - 0.20, 1.56), bevel=0.02), "wood_dark")
    brace(a, 1.30, YF - 0.18, 1.40, length=0.38, angle=58, axis="x")
    a.add(p_cyl(0.03, 0.03, 0.17, 6, loc=(1.30, -1.76, 1.34)), "rope")
    # окорок: сплюснутая по XY икосфера + jitter, чтобы не читалась как ровный шар
    a.add(p_ico(0.17, sub=2, loc=(1.30, -1.76, 1.24), scl=(0.80, 0.80, 1.35), jitter=0.05),
          "copper")

    # --- сеновал: люк во фронтоне и балка подъёмника над ним ---------------------
    a.add(p_box((0.80, 0.16, 0.70), loc=(0, YF - 0.04, 2.52), bevel=0.03), "wood_dark")
    a.add(p_box((0.58, 0.12, 0.50), loc=(0, YF - 0.10, 2.52), bevel=0.0), "black")
    a.add(p_box((0.13, 0.46, 0.12), loc=(0, YF - 0.20, 2.99), bevel=0.025), "wood_dark")
