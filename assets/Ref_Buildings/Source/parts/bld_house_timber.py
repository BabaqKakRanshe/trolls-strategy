"""
Дом с каменным низом и фахверковым верхом. От Bld_Cottage уходит сразу по трём осям:
выше, двухцветный и с открытым каркасом — иначе на контактном листе два жилых дома
читались бы как один ассет с разной кровлей.
"""
import math

from build_vitaria import p_box, by_normal
from parts.common import (chimney, cornice, gable_roof, gable_wall, plank_door,
                          stone_base, window)

NAME = "Bld_House_Timber"
TARGET = (3.6, 3.1, 3.7)     # w, d, h в метрах

W1, D1 = 2.60, 2.25          # каменный первый этаж
W2, D2 = 2.70, 2.35          # верх свисает на 5 см с каждой стороны — подпись фахверка
F, Z1, Z2 = 0.24, 1.15, 2.35
FT = 0.12                    # брус каркаса: тоньше 10 см на игровой дистанции пропадает
ZMID = 1.68                  # межэтажный ригель делит верх на глухую панель и панель с окнами
WOOD = "wood_dark"
CHY = 0.78                   # труба сдвинута к +Y, чтобы не сесть на боковое окно и угловую стойку


def build(a):
    # --- низ: камень на цоколе. by_normal светлит верхние грани, контраст даёт не свет, а палитра
    stone_base(a, W1 + 0.26, D1 + 0.26)
    a.add(p_box((W1, D1, Z1 - F), loc=(0, 0, (F + Z1) / 2), bevel=0.05),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))
    # угловые квадры: без них первый этаж был серым пятном под богатым верхом.
    # Утоплены внутрь габарита камня, иначе они съели бы нависание верхнего этажа.
    for sx in (-1, 1):
        for sy in (-1, 1):
            a.add(p_box((0.20, 0.20, Z1 - F), loc=(sx * (W1 / 2 - 0.07), sy * (D1 / 2 - 0.07),
                                                   (F + Z1) / 2), bevel=0.04), "stone_light")

    # --- верх: штукатурка по нависающему объёму; балка-перепуск прячет уступ жилья над камнем
    a.add(p_box((W2, D2, Z2 - Z1), loc=(0, 0, (Z1 + Z2) / 2), bevel=0.04), "wood_pale")
    cornice(a, W2, D2, Z1, t=0.16, col=WOOD)

    zc = (Z1 + Z2) / 2
    hlow = ZMID - 0.07 - Z1                 # глухая панель под ригелем
    zlow = (Z1 + ZMID - 0.07) / 2
    dlen = hlow * math.sqrt(2)              # раскос ровно по высоте панели, поэтому угол 45°

    # угловые стойки торчат в обе стороны: каркасный силуэт держится с любого ракурса
    for sx in (-1, 1):
        for sy in (-1, 1):
            a.add(p_box((0.20, 0.20, Z2 - Z1), loc=(sx * W2 / 2, sy * D2 / 2, zc), bevel=0.035), WOOD)

    # --- каркас на фасадных гранях (-Y/+Y). Стойки и раскос живут в нижней панели,
    # окна — в верхней, поэтому со ставнями они не спорят.
    fy = D2 / 2 - 0.03                      # брус выходит на 3 см из штукатурки
    for sy in (-1, 1):
        a.add(p_box((W2 - 0.24, FT, 0.14), loc=(0, sy * fy, ZMID), bevel=0.025), WOOD)
        for sx in (-1, 1):
            a.add(p_box((FT, FT, hlow), loc=(sx * 0.95, sy * fy, zlow), bevel=0.02), WOOD)
        # средник над ригелем: без него два окна со ставнями сливались в одну синюю ленту
        a.add(p_box((FT, FT, 2.26 - ZMID - 0.07), loc=(0, sy * fy, (ZMID + 0.07 + 2.26) / 2),
                    bevel=0.02), WOOD)
        # один раскос на грань: второй превращает стену в решётку и съедает силуэт
        a.add(p_box((FT, FT, dlen), loc=(sy * -0.50, sy * fy, zlow),
                    rot=(0, sy * 45, 0), bevel=0.02), WOOD)

    # --- каркас на боковых гранях; стойки чуть ближе к центру, чтобы труба их не съела
    fx = W2 / 2 - 0.03
    for sx in (-1, 1):
        a.add(p_box((FT, D2 - 0.24, 0.14), loc=(sx * fx, 0, ZMID), bevel=0.025), WOOD)
        for sy in (-1, 1):
            a.add(p_box((FT, FT, hlow), loc=(sx * fx, sy * 0.45, zlow), bevel=0.02), WOOD)
        a.add(p_box((FT, FT, dlen), loc=(sx * fx, 0, zlow),
                    rot=(sx * 45, 0, 0), bevel=0.02), WOOD)

    # --- верхний пояс и кровля. Пояс поднят до 2.32: ниже он спорил бы с окнами,
    # выше — вылез бы сквозь скат.
    cornice(a, W2, D2, 2.32, t=0.12, col=WOOD)
    zr = gable_roof(a, W2, D2, Z2, pitch_deg=38)
    gable_wall(a, W2, Z2, zr, D2, col="wood_pale")

    # фронтон тоже фахверковый: затяжка и две стойки, обрезанные по скату
    hg = (zr - 0.08 - Z2) * (1 - 0.52 / (W2 / 2))
    for sy in (-1, 1):
        yg = sy * (D2 / 2 - 0.02)
        a.add(p_box((1.42, 0.10, 0.13), loc=(0, yg, Z2 + 0.42), bevel=0.02), WOOD)
        for sx in (-1, 1):
            a.add(p_box((FT, 0.10, hg), loc=(sx * 0.52, yg, Z2 + hg / 2), bevel=0.02), WOOD)

    # --- труба выведена выше конька: остановленная в скате труба — классическая ошибка.
    # Ствол широкий: на первом рендере 0.40 читалось трубой котельной, а не кладкой.
    chimney(a, W2 / 2 - 0.04, CHY, 1.00, h=2.92, w=0.50)
    # печной выступ доведён до цоколя: на консоли ствол висел в воздухе над камнем,
    # а так труба стоит на земле и заодно объясняет разрыв фахверка на этой грани
    a.add(p_box((0.46, 0.54, 1.26), loc=(W2 / 2 - 0.06, CHY, 0.60), bevel=0.05), "stone_mid")
    a.add(p_box((0.60, 0.66, 0.12), loc=(W2 / 2 - 0.04, CHY, 1.17), bevel=0.04), "stone_dark")

    # --- дверь на фасаде. Полотно низкое: первый этаж всего 0.91 м, высокое вылезло бы
    # в нависающий верх, а не под балку.
    yd = -D1 / 2
    plank_door(a, yd, F, w=0.60, h=0.82)
    a.add(p_box((1.02, 0.44, 0.16), loc=(0, yd - 0.22, 0.07), bevel=0.04), "stone_light")

    # два окна верхнего этажа на фасад
    yw = -D2 / 2 + 0.03
    for sx in (-1, 1):
        window(a, (sx * 0.66, yw, 2.00), w=0.36, h=0.32, sill=False)

    # боковые окна: ставни window() смещаются по мировому X, у повёрнутого окна они улетели бы
    # от стены, поэтому ставни и стекло ставим вдоль стены руками
    for sx in (-1, 1):
        window(a, (sx * (W2 / 2 + 0.02), -0.05, 2.00), rot=(0, 0, 90),
               w=0.44, h=0.32, shutters=False, sill=False)
        a.add(p_box((0.09, 0.40, 0.30), loc=(sx * (W2 / 2 + 0.06), -0.05, 2.00), bevel=0.02), "glass")
        for sy in (-1, 1):
            a.add(p_box((0.09, 0.24, 0.42), loc=(sx * (W2 / 2 + 0.07), -0.05 + sy * 0.36, 2.00),
                        bevel=0.025), "roof_dark")
