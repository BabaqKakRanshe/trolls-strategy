"""
Каменный дом с арочным входом — рустованный «старший брат» Bld_Cottage:
выше, весь в камне, дверь смещена влево и обрамлена аркой.
"""
from build_vitaria import p_box, p_cyl, by_normal
from parts.common import (arch_door, chimney, cornice, gable_roof, gable_wall,
                          window)

NAME = "Bld_House_Stone"
TARGET = (3.4, 2.9, 3.5)   # w, d, h в метрах


def build(a):
    W, D, F = 2.55, 2.20, 0.26
    # Верх стен 2.00, а не 1.85: каменный портал arch_door поднимается на w/2+0.17
    # выше проёма, и при 1.85 арка пробивала бы карниз. Заодно дом выше коттеджа.
    ZT = 2.00
    H = ZT - F

    # цоколь шире корпуса на 0.18/0.15 на сторону — на него ложатся угловые русты
    a.add(p_box((2.90, 2.50, 0.40), loc=(0, 0, 0.06), bevel=0.06), "stone_dark")
    # весь корпус каменный, контраст верх/бок/низ даёт by_normal, а не свет
    a.add(p_box((W, D, H), loc=(0, 0, F + H / 2), bevel=0.05),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # Руст: 5 блоков на угол, длинная сторона чередуется — блок то тянется по X,
    # то по Y. Выступ разный (7 и 3 см) намеренно: при равном выступе грань блока
    # совпала бы с гранью стены и замерцала бы на общем UV.
    for i in range(5):
        z = F + (i + 0.5) * H / 5
        long_x = i % 2 == 0
        size = (0.44, 0.30, 0.32) if long_x else (0.30, 0.44, 0.32)
        dx = W / 2 - (0.19 if long_x else 0.08)
        dy = D / 2 - (0.08 if long_x else 0.19)
        for sx in (-1, 1):
            for sy in (-1, 1):
                a.add(p_box(size, loc=(sx * dx, sy * dy, z), bevel=0.045), "stone_light")

    # карниз каменный, а не дощатый: на этом доме дерева почти нет
    cornice(a, W, D, ZT - 0.05, col="stone_light")

    zr = gable_roof(a, W, D, ZT, pitch_deg=38)
    gable_wall(a, W, ZT, zr, D, col="stone_mid")
    # труба со стороны -X; подошва спрятана в стене, верх на 15 см выше конькового
    # гребня — иначе на общем листе труба сливается с кровлей
    chimney(a, -W / 2 + 0.36, 0.42, 1.90, h=1.64, w=0.44)

    yf = -D / 2
    # дверь сдвинута влево: асимметрия фасада — главное отличие от коттеджа.
    # h=1.06 вместо 1.25 подобрано так, чтобы верх каменной арки (z0+h+w/2+0.17)
    # остался под карнизом.
    arch_door(a, y=yf, z0=F, w=0.68, h=1.06, x=-0.45)
    # Накладная филёнка. В arch_door передняя грань полотна и торец арочного
    # цилиндра лежат ровно в одной плоскости, и Cycles рисует их пересечение
    # чёрным пятном самозатенения. Филёнка выходит на 1.7 см вперёд и закрывает
    # это место, заодно делая дверь двуцветной. Поперечины остаются выше неё.
    a.add(p_box((0.66, 0.05, 1.08), loc=(-0.45, yf - 0.1425, F + 0.54), bevel=0.012),
          "wood_light")
    # ступень-плита перед порогом: пол на 0.26, одного подступёнка достаточно
    a.add(p_box((1.20, 0.44, 0.18), loc=(-0.45, yf - 0.22, 0.09), bevel=0.05), "stone_light")

    # Ставни везде выключены. На фасаде они упирались бы в руст, а при rot=(0,0,90)
    # window() смещает их по X независимо от поворота — сбоку они отлетают от стены.
    window(a, (0.55, yf + 0.02, F + 0.95), w=0.40, h=0.48, shutters=False)
    window(a, (0.0, yf + 0.02, 2.44), w=0.34, h=0.36, shutters=False)
    for sx in (-1, 1):
        window(a, (sx * (W / 2 + 0.02), 0.15, F + 0.95), rot=(0, 0, 90),
               w=0.42, h=0.48, shutters=False)
        # Стекло внутри window() смещается на y-0.03, и при rot=90 это смещение
        # уходит вдоль проёма, и стекло целиком тонет в наличнике. Ставим его сами.
        a.add(p_box((0.42, 0.09, 0.48), loc=(sx * (W / 2 + 0.07), 0.15, F + 0.95),
                    rot=(0, 0, 90), bevel=0.02), "glass")

    # Фонарь слева от портала — единственное тёплое пятно на сером доме.
    # Кронштейн уходит в угловой руст, поэтому лампа висит, а не парит.
    a.add(p_box((0.07, 0.26, 0.07), loc=(-0.91, yf - 0.13, 1.66), bevel=0.02), "wood_dark")
    a.add(p_cyl(0.11, 0.0, 0.07, 4, loc=(-0.91, yf - 0.20, 1.55), spin=45), "iron_dark")
    a.add(p_box((0.12, 0.12, 0.14), loc=(-0.91, yf - 0.20, 1.48), bevel=0.02), "lantern_glow")
    a.add(p_box((0.15, 0.15, 0.05), loc=(-0.91, yf - 0.20, 1.385), bevel=0.02), "iron_dark")
