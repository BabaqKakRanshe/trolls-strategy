"""Круглая башня с деревянной галереей: каменный ствол, балкон на кронштейнах, синий конус."""
import math

from build_vitaria import p_box, p_cyl, p_ico, by_normal
from parts.common import arch_door, banner

NAME = "Bld_Tower_Round"
TARGET = (2.9, 2.9, 6.3)   # w, d, h в метрах

SEG = 12
# spin=15 сдвигает 12-угольник так, что центр грани приходится ровно на -Y и на оси X:
# фасаду нужна плоская площадка под каменный портал, иначе портал сядет на ребро.
SPIN = 15.0

STONE = by_normal("stone_light", "stone_mid", "stone_dark", 0.8)
Z_DECK = 3.72            # низ настила галереи
Z_WALK = Z_DECK + 0.16   # ходовая поверхность галереи


def build(a):
    # Цоколь шире ствола и темнее — башня должна сесть в землю, а не стоять трубой.
    a.add(p_cyl(1.15, 1.10, 0.34, SEG, loc=(0, 0, -0.12), spin=SPIN, bevel=0.04),
          by_normal("stone_mid", "stone_dark", "stone_dark", 0.8))

    # Ствол с лёгким сбегом: силуэт перестаёт читаться как ровный цилиндр.
    a.add(p_cyl(1.00, 0.94, 3.60, SEG, loc=(0, 0, 0.20), spin=SPIN, bevel=0.03), STONE)

    # Поясок делит высокую глухую стену надвое — единственная горизонталь ниже галереи.
    a.add(p_cyl(1.09, 1.05, 0.20, SEG, loc=(0, 0, 1.90), spin=SPIN, bevel=0.04), STONE)

    # Кронштейны: именно они объясняют, на чём держится галерея, поэтому их 12 — по одному
    # на грань. Нижний конец утоплен в стену, верхний уходит в настил: ничего не висит.
    for i in range(SEG):
        ang = 2 * math.pi * i / SEG
        a.add(p_box((0.18, 0.22, 0.88), loc=(1.03 * math.cos(ang), 1.03 * math.sin(ang), 3.48),
                    rot=(0, 45, math.degrees(ang)), bevel=0.025), "wood_dark")

    # Настил галереи: верх светлый, свес снизу тёмный — контраст даёт by_normal, не свет.
    a.add(p_cyl(1.42, 1.42, 0.16, SEG, loc=(0, 0, Z_DECK), spin=SPIN, bevel=0.03),
          by_normal("wood_light", "wood_mid", "wood_dark", 0.7))

    for i in range(SEG):
        ang = 2 * math.pi * i / SEG
        a.add(p_box((0.10, 0.12, 0.42), loc=(1.30 * math.cos(ang), 1.30 * math.sin(ang), Z_WALK + 0.21),
                    rot=(0, 0, math.degrees(ang)), bevel=0.02), "wood_dark")
        # Прогоны набраны отрезками по хорде между стойками. p_cyl здесь нельзя:
        # тонкий цилиндр на 12 сегментов — это диск, он накрыл бы галерею второй крышей.
        mid = ang + math.pi / SEG
        for zr in (Z_WALK + 0.19, Z_WALK + 0.38):
            a.add(p_box((0.09, 0.70, 0.09), loc=(1.256 * math.cos(mid), 1.256 * math.sin(mid), zr),
                        rot=(0, 0, math.degrees(mid)), bevel=0.02), "wood_mid")

    # Верхний узкий барабан: он поднимает конус над перилами, иначе кровля садится на них.
    a.add(p_cyl(0.86, 0.82, 0.88, SEG, loc=(0, 0, 3.86), spin=SPIN, bevel=0.03), STONE)

    # Бойницы. arrow_slit() сдвигает тёмный проём в мировой -Y, и на боковых гранях круглой
    # стены он утонул бы в камне, поэтому смещение здесь считается по радиусу наружу.
    # rf — радиус грани на этой высоте с учётом сбега ствола, иначе рамка отрывается от стены.
    for deg, z, h, rf in ((210, 2.80, 0.60, 0.90), (330, 2.50, 0.52, 0.91),
                          (270, 4.24, 0.44, 0.79), (180, 4.24, 0.44, 0.79)):
        cx, cy = math.cos(math.radians(deg)), math.sin(math.radians(deg))
        yaw = deg + 90   # тонкая ось локального Y обязана смотреть наружу, как в window() кита
        a.add(p_box((0.28, 0.12, h + 0.16), loc=(rf * cx, rf * cy, z), rot=(0, 0, yaw), bevel=0.03),
              "stone_light")
        a.add(p_box((0.12, 0.10, h), loc=((rf + 0.035) * cx, (rf + 0.035) * cy, z),
                    rot=(0, 0, yaw), bevel=0.0), "black")

    # Юбка под свесом конуса. Первый рендер показал, что узкое кольцо на 4.58 целиком
    # пряталось за конусом: полосу опустили и расширили, теперь карниз читается сам по себе.
    a.add(p_cyl(1.34, 1.26, 0.26, SEG, loc=(0, 0, 4.48), spin=SPIN, bevel=0.04), "roof_dark")
    a.add(p_cyl(1.22, 0.0, 1.50, SEG, loc=(0, 0, 4.70), spin=SPIN, bevel=0.03), "roof")
    a.add(p_ico(0.12, sub=1, loc=(0, 0, 6.18)), "gold")

    # Фасад в -Y. Портал утоплен на 0.06 от центра грани, чтобы его углы не отрывались
    # от соседних граней 12-угольника: там стена ближе к нулю на 0.07.
    arch_door(a, -0.88, 0.22, w=0.56, h=1.05)
    # Ступень перекрывает вынос цоколя — без неё порог на 0.22 висит за каменным свесом.
    a.add(p_box((1.00, 0.46, 0.18), loc=(0, -1.22, 0.07), bevel=0.04), "stone_light")

    # Хоругвь прижата к стене фасада, а не подвешена к галерее: на весу она резала кронштейн
    # и закрывала бойницу. Верх опущен до 3.10 — на 3.25 она слипалась с кронштейнами галереи.
    banner(a, (0, -0.975, 3.10), w=0.52, h=0.82, pole=False)
