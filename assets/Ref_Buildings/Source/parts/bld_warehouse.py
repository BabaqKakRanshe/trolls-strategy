"""Склад: каменный цоколь, деревянный каркас и огромная кровля над открытым фасадом."""
from build_vitaria import p_box, p_cyl, by_normal
from parts.common import (gable_roof, gable_wall, cornice, gate, post, brace,
                          stone_base, crate, barrel)

NAME = "Bld_Warehouse"
TARGET = (5.6, 4.0, 4.3)   # w, d, h в метрах

W, D = 4.2, 3.2            # след каркаса; кровля свисает за него и даёт габарит 5.3 м
ZP, ZT = 0.55, 2.35        # верх цоколя (он же пол склада) и верх стоек
PX = (-2.1, -1.1, 1.1, 2.1)  # шаг стоек по длинной стороне: центральный пролёт 2.2 м под ворота


def build(a):
    # Цоколь двумя уступами: широкая подошва тёмная, тело светлее сверху за счёт by_normal —
    # верхняя плоскость работает полом открытого отсека, поэтому её видно и она обязана читаться.
    stone_base(a, W + 0.30, D + 0.30, h=0.22)
    a.add(p_box((W, D, ZP - 0.21), loc=(0, 0, (ZP + 0.21) / 2), bevel=0.05),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # Каркас. Стойки по обеим длинным сторонам в одинаковом шаге: ритм стоек — единственное,
    # что связывает закрытую заднюю стену с открытым фасадом.
    for x in PX:
        for sy in (-1, 1):
            post(a, x, sy * D / 2, ZP, ZT - ZP, s=0.22)
    for sx in (-1, 1):       # промежуточная стойка на короткой стороне: 3.2 м обшивки без неё провисают
        post(a, sx * W / 2, 0.0, ZP, ZT - ZP, s=0.22)

    cornice(a, W, D, 2.33, t=0.18)   # верхняя обвязка; её низ 2.24 — ровно под перемычкой ворот

    # Обшивка задней стены и боков между стойками. Дощатые щиты тоньше стоек,
    # поэтому каркас остаётся читаемым рельефом, а не сливается со стеной.
    for xc, lw in ((-1.6, 0.8), (0.0, 2.0), (1.6, 0.8)):
        a.add(p_box((lw, 0.14, ZT - ZP), loc=(xc, D / 2, (ZP + ZT) / 2), bevel=0.03), "wood_mid")
    for sx in (-1, 1):
        for yc in (-0.8, 0.8):
            a.add(p_box((0.14, 1.4, ZT - ZP), loc=(sx * W / 2, yc, (ZP + ZT) / 2), bevel=0.03), "wood_mid")
    # Средний пояс по трём закрытым сторонам: одна горизонталь ломает высокий щит надвое
    a.add(p_box((W - 0.2, 0.18, 0.16), loc=(0, D / 2, 1.45), bevel=0.03), "wood_dark")
    for sx in (-1, 1):
        a.add(p_box((0.18, D - 0.2, 0.16), loc=(sx * W / 2, 0, 1.45), bevel=0.03), "wood_dark")

    # Угловые раскосы фасада: на открытой стороне они и есть вся конструктивная логика,
    # низ упирается во внутреннюю грань стойки, верх — в низ обвязки.
    for sx in (-1, 1):
        brace(a, sx * 1.771, -D / 2, 2.021, length=0.62, angle=-sx * 45, axis="y")

    # Кровля намеренно переразмерена: на референсе склад — это прежде всего крыша,
    # свесы 0.45/0.40 уводят её далеко за каркас и затеняют открытый отсек.
    zr = gable_roof(a, W, D, ZT, ox=0.45, oy=0.40, bands=3)
    gable_wall(a, W, ZT, zr, D, col="wood_light")

    # Ворота в центральном пролёте, отодвинуты от плоскости стоек под свес крыши
    gate(a, y=-D / 2 + 0.15, z0=ZP, w=1.6, h=1.40)
    # Два каменных уступа: без них пол на 0.55 м и ворота висят над землёй
    a.add(p_box((2.2, 0.34, 0.34), loc=(0, -2.00, 0.03), bevel=0.05), "stone_light")
    a.add(p_box((2.2, 0.34, 0.52), loc=(0, -1.75, 0.12), bevel=0.05), "stone_light")

    # Груз в открытых боковых пролётах — он и объясняет, что это склад.
    # Ящики разведены и по Y, и по X: поставленные в затылок друг другу они с игровой
    # камеры сливались в одну колонну, и штабель «два и один» не читался.
    crate(a, (-1.74, -1.22, ZP), s=0.42)
    crate(a, (-1.48, -0.78, ZP), s=0.42)
    crate(a, (-1.64, -1.02, ZP + 0.42), s=0.42, rot=(0, 0, 20))
    # Лежачая бочка вынесена к самому устью пролёта и положена вдоль фасада: в глубине
    # отсека она тонула в тени, а торцом к зрителю читалась как диск, а не как бочка.
    # p_cyl растёт от loc по локальной Z, rot=(0,90,0) уводит её в +X, ось поднята на радиус.
    barrel(a, (1.28, -1.36, ZP + 0.23), r=0.23, h=0.50, rot=(0, 90, 0))
    # Стоячие бочки прижаты к разным сторонам пролёта: выстроенные в одну линию они
    # перекрывали друг друга и в тени отсека сливались в одно тёмное пятно
    barrel(a, (1.74, -0.92, ZP), r=0.23, h=0.50)
    barrel(a, (1.48, -0.42, ZP), r=0.23, h=0.50)

    # Подъёмная балка из-под конька на фасад с подкосом в фронтон и короткой верёвкой:
    # длиннее делать нельзя — вылет за свес крыши начинает читаться как ошибка
    a.add(p_box((0.15, 0.78, 0.15), loc=(0, -1.87, 3.40), bevel=0.03), "wood_dark")
    brace(a, 0, -1.675, 3.16, length=0.42, angle=38, axis="x")
    a.add(p_cyl(0.028, 0.028, 0.55, 6, loc=(0, -2.08, 2.79)), "rope")
    a.add(p_box((0.10, 0.10, 0.12), loc=(0, -2.08, 2.76), bevel=0.02), "iron_dark")
