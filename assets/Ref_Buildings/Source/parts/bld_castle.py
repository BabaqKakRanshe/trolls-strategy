"""Замок — центр города: круглый донжон слева, воротный блок в середине, жилой корпус справа."""
from build_vitaria import p_box, p_cyl, by_normal
from parts.common import (arrow_slit, banner, battlements, chimney, cornice, flag_pole,
                          gable_roof, gable_wall, gate, round_battlements, window)

NAME = "Bld_Castle"
TARGET = (6.8, 5.0, 7.6)   # w, d, h в метрах

# Оси трёх масс. Замок — единственное составное здание листа, поэтому координаты вынесены
# в константы: при подгонке габарита иначе пришлось бы править числа в двадцати местах.
TX, TY = -2.00, -0.45      # донжон
GX, GY = -0.15, -0.20      # воротный блок вынесен вперёд: надвратная башня обязана
                           # выступать из фронта, иначе её парапет тонет между донжоном и жильём
HX, HY = 2.00, -0.13       # жилой корпус
KX, KY = 0.72, 1.75        # угловая турель за стыком ворот и жилья
GW, GD, GH = 2.60, 2.90, 2.40
HW, HD, HT = 2.40, 2.40, 3.00
YG = GY - GD / 2           # фасад воротного блока
YH = HY - HD / 2           # фасад жилья стоит на своей плоскости, не заподлицо с воротами:
                           # совпадающие грани двух пересекающихся коробок дают z-fighting


class _At:
    """Детали common.py всегда собираются вокруг начала координат, а здесь три массы стоят
    в разных местах. Сдвигаем готовую деталь прокси-объектом — дублировать gable_roof и
    battlements ради смещения дороже, чем один адаптер."""

    def __init__(self, a, dx=0.0, dy=0.0):
        self.a, self.dx, self.dy = a, dx, dy

    def add(self, part, color, smooth=False):
        for v in part.verts:
            v.co.x += self.dx
            v.co.y += self.dy
        self.a.add(part, color, smooth)


def build(a):
    stone = by_normal("stone_light", "stone_mid", "stone_dark", 0.8)
    timber = by_normal("wood_light", "wood_mid", "wood_dark", 0.8)

    # --- ДОНЖОН -------------------------------------------------------------------------
    # Цоколь шире ствола: без него цилиндр выглядит вкопанной трубой.
    a.add(p_cyl(1.38, 1.30, 0.45, 12, loc=(TX, TY, -0.14), bevel=0.05), stone)
    a.add(p_cyl(1.15, 1.15, 4.20, 12, loc=(TX, TY, 0.20), bevel=0.05), stone)
    # Поясок под зубцами тёмный — он же граница, по которой глаз читает высоту башни.
    a.add(p_cyl(1.27, 1.27, 0.20, 12, loc=(TX, TY, 3.94), bevel=0.04), "stone_dark")
    round_battlements(_At(a, TX, TY), 1.15, 4.40, n=12, bw=0.34, bh=0.46)
    # Узкий барабан внутри венца зубцов: кровля должна опираться на него, а не висеть.
    a.add(p_cyl(0.92, 0.92, 0.56, 12, loc=(TX, TY, 4.38), bevel=0.04), stone)
    a.add(p_cyl(1.32, 1.28, 0.22, 12, loc=(TX, TY, 4.86)), "roof_dark")
    a.add(p_cyl(1.25, 0.0, 1.50, 12, loc=(TX, TY, 4.98), bevel=0.04), "roof")
    flag_pole(a, TX, TY, 6.36, h=1.10, col="cream")
    # Бойницы на -Y: сдвиг 1.13 при радиусе плоской грани 1.11 — рамка чуть выступает из ствола.
    for z in (1.55, 2.85):
        arrow_slit(a, (TX, TY - 1.13, z), h=0.62)

    # --- ВОРОТНЫЙ БЛОК ------------------------------------------------------------------
    # Цоколь утоплен по -Y на 10 см: выступи он вперёд — упёрся бы в портал ворот.
    a.add(p_box((GW + 0.22, GD - 0.04, 0.40), loc=(GX, GY + 0.08, 0.06), bevel=0.05), "stone_dark")
    a.add(p_box((GW, GD, GH + 0.14), loc=(GX, GY, (GH - 0.14) / 2), bevel=0.05), stone)
    cornice(_At(a, GX, GY), GW, GD, 2.22, t=0.16, col="stone_dark")
    # Зубцы мельче и чаще умолчания: при bw=0.40 на 2.6 м их выходит три штуки
    # с метровыми промежутками — парапет читался россыпью кубиков, а не стеной.
    battlements(_At(a, GX, GY), GW, GD, GH, bw=0.30, bh=0.44, gap=0.26)

    gate(a, y=YG - 0.06, z0=0.0, w=1.30, h=1.75, x=GX)
    # Порог: ворота обязаны быть достижимы с земли, а не начинаться с уступа цоколя.
    a.add(p_box((1.90, 0.46, 0.18), loc=(GX, YG - 0.21, 0.05), bevel=0.04), "stone_light")
    # Хоругви разведены за габарит перемычки (та доходит до x=-1.05 и 0.75) и опущены под неё,
    # иначе полотно и камень дерутся за одни пиксели. Древко снято — висят прямо на стене.
    for sx in (-1, 1):
        banner(a, (GX + sx * 1.10, YG - 0.03, 2.00), w=0.34, h=1.10, col="roof", pole=False)

    # --- ЖИЛОЙ КОРПУС -------------------------------------------------------------------
    a.add(p_box((HW + 0.22, HD + 0.22, 0.38), loc=(HX, HY, 0.05), bevel=0.05), "stone_dark")
    a.add(p_box((HW, HD, 1.69), loc=(HX, HY, 0.705), bevel=0.05), stone)
    cornice(_At(a, HX, HY), HW, HD, 1.57, t=0.16, col="wood_dark")
    # Брус с напуском 5 см: ступенька на стыке камня и дерева даёт тень без света.
    a.add(p_box((HW + 0.10, HD + 0.10, 1.45), loc=(HX, HY, 2.275), bevel=0.05), timber)
    # Верх стен поднят до 3.0, а уклон взят 42 вместо 36: свес обязан пройти НАД зубцами
    # ворот (2.84), иначе мерлоны протыкают скат насквозь — так и было в первом рендере.
    zr = gable_roof(_At(a, HX, HY), HW, HD, HT, pitch_deg=42.0, ox=0.16, oy=0.10)
    gable_wall(_At(a, HX, HY), HW, HT, zr, HD, col="wood_mid")
    chimney(a, HX + 0.80, HY + 0.62, 2.80, h=1.35, w=0.42)
    for sx in (-1, 1):
        window(a, (HX + sx * 0.62, YH + 0.02, 2.25), w=0.44, h=0.52)

    # --- УГЛОВАЯ ТУРЕЛЬ ------------------------------------------------------------------
    # Заходит в заднюю стену воротного блока: турель должна прирастать к замку,
    # а не стоять рядом. Высоты цоколей разведены (0.26 / 0.24 / 0.30) — снова против z-fighting.
    a.add(p_cyl(0.74, 0.70, 0.42, 10, loc=(KX, KY, -0.12), bevel=0.04), "stone_dark")
    a.add(p_cyl(0.62, 0.62, 3.06, 10, loc=(KX, KY, 0.0), bevel=0.04), stone)
    round_battlements(_At(a, KX, KY), 0.62, 3.06, n=8, bw=0.26, bh=0.36)
    a.add(p_cyl(0.84, 0.82, 0.16, 10, loc=(KX, KY, 3.20)), "roof_dark")
    a.add(p_cyl(0.80, 0.0, 0.85, 10, loc=(KX, KY, 3.28), bevel=0.03), "roof")
