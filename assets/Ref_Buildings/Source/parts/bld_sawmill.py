"""Пилорама: открытый навес с большой циркулярной пилой и штабелем брёвен справа."""
import math

from build_vitaria import p_box, p_cyl, p_ico, by_normal
from parts.common import (brace, chimney, cornice, gable_roof, gable_wall,
                          log_piece, post, stone_base)

NAME = "Bld_Sawmill"
TARGET = (5.0, 3.4, 3.9)   # w, d, h в метрах


def build(a):
    W, D, F, ZT = 3.4, 2.8, 0.28, 2.10   # F — уровень настила, ZT — верх стоек
    PX, PY = 1.55, 1.25                  # оси стоек: внутри кромки цоколя

    # Цоколь + отдельная плита настила: stone_base красит всё одним swatch-ем,
    # а у навеса пол — самая большая видимая грань, ей нужен светлый верх.
    stone_base(a, W, D)
    a.add(p_box((W - 0.2, D - 0.2, 0.16), loc=(0, 0, F - 0.08), bevel=0.04),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # Шесть стоек: четыре угловые и две в середине боковых стен. Средняя стойка
    # на фасаде закрывала бы пилу ровно по центру — а открытый фасад тут и есть смысл,
    # поэтому пролёт по -Y отдан обвязке и угловым раскосам.
    # Сечение 0.18 против 0.20 у обвязки и верх на 4 см ниже её верха: совпадающие
    # грани стойки и пояса давали z-fighting — чёрный квадрат в месте примыкания.
    for sy in (-1, 1):
        post(a, -PX, sy * PY, F, ZT - F - 0.04, s=0.18, col="wood_mid")
        post(a, PX, sy * PY, F, ZT - F - 0.04, s=0.18, col="wood_mid")
    for sx in (-1, 1):
        post(a, sx * PX, 0.0, F, ZT - F - 0.04, s=0.18, col="wood_mid")

    # Обвязка по верху стоек — тёмный пояс, который держит силуэт навеса
    cornice(a, 2 * PX, 2 * PY, ZT - 0.09, t=0.18)

    # Раскосы в обеих плоскостях: в XZ — на угловых стойках, в YZ — на средних.
    # Без них снятая фасадная стойка оставила бы каркас «на честном слове».
    for sx in (-1, 1):
        for sy in (-1, 1):
            brace(a, sx * 1.32, sy * PY, 1.80, length=0.62, angle=-sx * 45)
            brace(a, sx * PX, sy * 0.22, 1.80, length=0.62, angle=-sy * 45, axis="x")

    # Задняя стена (+Y) обшита горизонтальными досками снаружи стоек:
    # y=1.40 ставит доски заподлицо с наружной гранью стойки, без взаимного вреза.
    for i in range(6):
        z = F + 0.15 + i * 0.305
        a.add(p_box((2 * PX + 0.2, 0.10, 0.32), loc=(0, 1.40, z), bevel=0.025),
              "wood_light" if i % 2 else "wood_mid")

    # Кровля с большим свесом: она и есть «крыша над станком», под ней сухо
    zr = gable_roof(a, W, D, ZT, ox=0.35, oy=0.30)
    # inset/depth увеличены: фронтон обязан перекрыть всю глубину обвязки,
    # иначе над плитой остаётся щель и на фасаде видны чёрные провалы.
    gable_wall(a, W, ZT, zr, D, col="wood_light", inset=0.14, depth=0.30)

    # Труба котла проходит сквозь скат — так и стоит настоящая дымовая труба;
    # отнести её за габарит навеса значило бы оторвать от здания.
    chimney(a, -1.30, 0.85, F, h=2.85, w=0.50)

    # ---- станок ----------------------------------------------------------------
    # Стол разрезан на две половины: щель 0.09 м по y=0 — это пропил, из которого
    # выходит диск. Цельная столешница заставляла бы пилу торчать сквозь дерево.
    for sy in (-1, 1):
        a.add(p_box((1.5, 0.305, 0.16), loc=(0, sy * 0.1975, 0.75), bevel=0.03), "wood_mid")
    for sx in (-1, 1):
        a.add(p_box((0.15, 0.62, 0.70 - F), loc=(sx * 0.55, 0, (F + 0.70) / 2), bevel=0.035), "wood_dark")
    # Связь козлов убрана за плоскость диска (+Y): спереди она перечёркивала пилу
    a.add(p_box((1.2, 0.10, 0.10), loc=(0, 0.20, 0.42), bevel=0.02), "wood_dark")

    # Диск: ось на z=0.62 — прямо под столешницей, поэтому над столом торчит
    # заметный сегмент 0.31 м, а низ диска уходит в цоколь, как в приямок станка.
    ZH, RB = 0.62, 0.52
    a.add(p_cyl(RB, RB, 0.05, 16, loc=(0, 0.025, ZH), rot=(90, 0, 0)), "iron_light")
    a.add(p_cyl(0.10, 0.10, 0.11, 10, loc=(0, 0.055, ZH), rot=(90, 0, 0)), "gold_dark")
    # Вал и подшипник только со стороны привода (+Y): симметричная пара брусьев
    # закрывала ступицу ровно с фасада, а фасад здесь — главный ракурс.
    a.add(p_cyl(0.05, 0.05, 0.44, 8, loc=(0, 0.44, ZH), rot=(90, 0, 0)), "iron_dark")
    a.add(p_box((0.16, 0.12, 0.34), loc=(0, 0.34, F + 0.17), bevel=0.025), "wood_dark")
    # Зубья без фаски и только на видимой дуге: ниже настила они всё равно в камне,
    # а фаска на кубике 6 см — чистая трата треугольников.
    for i in range(16):
        ang = 2 * math.pi * i / 16
        z = ZH + (RB + 0.035) * math.cos(ang)
        if z < F + 0.08:
            continue
        a.add(p_box((0.06, 0.05, 0.10), loc=((RB + 0.035) * math.sin(ang), 0.0, z),
                    rot=(0, math.degrees(ang), 0), bevel=0.0), "iron_dark")

    # Недопиленное бревно подано в диск: p_cyl растёт от loc вдоль +X, поэтому
    # x=-1.0 ставит торец ровно на ось пилы
    log_piece(a, (-1.00, 0.0, 1.00), r=0.17, L=1.00)

    # Куча опилок у стола — дешёвый признак работающей пилорамы
    a.add(p_ico(0.34, sub=2, loc=(1.02, -0.70, F + 0.04), scl=(1.1, 1.0, 0.30), jitter=0.16, cut=-0.04),
          by_normal("wood_pale", "wood_yellow", "wood_yellow", 0.4))

    # ---- штабель брёвен справа --------------------------------------------------
    # Бревна вдоль X, значит подкладки идут вдоль Y — поперёк брёвен.
    for x in (1.74, 2.52):
        a.add(p_box((0.16, 1.50, 0.14), loc=(x, 0, 0.07), bevel=0.03), "wood_dark")
    # Пирамида 4+3+2: шаг ряда 0.254 м — брёвна ложатся в ложбины нижнего ряда,
    # иначе штабель выглядит как сложенные в воздухе трубы.
    for row, n in enumerate((4, 3, 2)):
        z = 0.14 + 0.15 + row * 0.254
        for k in range(n):
            log_piece(a, (1.62, (k - (n - 1) / 2) * 0.32, z), r=0.15, L=1.05)

    # Прясло по кромке участка: три столба и две жердины, только чтобы читалась граница
    for y in (-1.0, 0.0, 1.0):
        post(a, 2.88, y, 0.0, 1.0, s=0.14)
    for z in (0.42, 0.78):
        a.add(p_box((0.10, 2.15, 0.12), loc=(2.88, 0, z), bevel=0.02), "wood_mid")
