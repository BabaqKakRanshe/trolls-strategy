"""
Казарма: широкий низкий форт-холл. Силуэт держит горизонталь — блок 5.6x2.7 под
зубчатым парапетом читается шире, чем выше, а синяя кровля намеренно пологая
(22 градуса): при крутом скате здание превращалось в жилой дом с большой крышей.
"""
import math
from build_vitaria import p_box, p_cyl, by_normal
from parts.common import (arrow_slit, banner, barrel, battlements, chimney, gable_roof_x,
                          gable_wall_x, gate, post, stone_base)

NAME = "Bld_Barracks"
TARGET = (6.2, 3.6, 4.4)   # w, d, h в метрах

W, D = 5.60, 2.70    # корпус: шире номинальных 5.2, иначе габарит не дотягивает до цели 6.2
F = 0.26             # верх цоколя, от него же начинается проём ворот
ZT = 2.60            # верх стены = низ зубцов; 10 см сверх номинала — запас над перемычкой ворот
BZ, BT = 2.36, 0.18  # каменный пояс: держим его на высоте перемычки ворот
YF = -D / 2          # фасад смотрит в -Y


def _sword(a, x, y, z, ang):
    """Меч на полотне хоругви. Координаты считаем по наклонной оси: p_box вращает
    блок вокруг своего центра, поэтому «поставить и повернуть» рукоять с клинком
    вместе нельзя — они бы разъехались. Разнос рукоятей 0.13 подобран так, чтобы
    клинки пересекались серединой, а не гардами: иначе в центре выходит ком."""
    s, c = math.sin(math.radians(ang)), math.cos(math.radians(ang))

    def at(t):
        return (x + s * t, y, z + c * t)

    a.add(p_box((0.085, 0.040, 0.25), loc=at(0.245), rot=(0, ang, 0), bevel=0.015), "iron_light")
    a.add(p_box((0.22, 0.045, 0.06), loc=at(0.105), rot=(0, ang, 0), bevel=0.018), "gold")
    a.add(p_box((0.055, 0.040, 0.15), loc=at(0.005), rot=(0, ang, 0), bevel=0.018), "wood_dark")


def _shield_rack(a, x0):
    """Стойка со щитами. Щиты прикусывают верхнюю жердь на 2 см: иначе на рендере
    они висят в воздухе, а зазор в 5 мм на игровой дистанции не читается как касание."""
    for sx in (-1, 1):
        post(a, x0 + sx * 0.56, -1.68, 0.0, 0.95, s=0.11)
    a.add(p_box((1.24, 0.12, 0.11), loc=(x0, -1.68, 0.90), bevel=0.025), "wood_mid")
    a.add(p_box((1.24, 0.10, 0.09), loc=(x0, -1.68, 0.34), bevel=0.02), "wood_mid")
    for i, col in ((-1, "roof"), (0, "iron_light"), (1, "roof")):
        x = x0 + i * 0.36
        a.add(p_box((0.30, 0.10, 0.38), loc=(x, -1.785, 0.68), bevel=0.035), col)
        a.add(p_cyl(0.055, 0.055, 0.05, 8, loc=(x, -1.80, 0.68), rot=(90, 0, 0)), "gold")


def _spear_rack(a):
    """Копья стоят на земле и опираются на жердь — так они не «растут» из воздуха."""
    for sx in (-1, 1):
        post(a, 2.28 + sx * 0.44, -1.62, 0.0, 0.86, s=0.10)
    a.add(p_box((1.02, 0.12, 0.10), loc=(2.28, -1.62, 0.80), bevel=0.025), "wood_mid")
    for i, (x, lean) in enumerate(((1.92, -7), (2.12, 5), (2.30, -4), (2.48, 6), (2.64, -3))):
        h = 1.40 + 0.09 * (i % 3)
        a.add(p_cyl(0.035, 0.030, h, 6, loc=(x, -1.70, 0.0), rot=(0, lean, 0)), "wood_mid")
        s = math.sin(math.radians(lean))
        c = math.cos(math.radians(lean))
        a.add(p_cyl(0.045, 0.0, 0.17, 6, loc=(x + s * h, -1.70, c * h), rot=(0, lean, 0)), "iron_light")


def build(a):
    # цоколь и каменный корпус; by_normal даёт светлый верх парапета без освещения
    stone_base(a, W + 0.40, D + 0.40, h=0.30)
    a.add(p_box((W, D, ZT - F), loc=(0, 0, (F + ZT) / 2), bevel=0.05),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # угловые пилястры выступают на 18 см — на игровой дистанции только они и держат углы
    for sx in (-1, 1):
        for sy in (-1, 1):
            a.add(p_box((0.36, 0.36, ZT - F), loc=(sx * W / 2, sy * D / 2, (F + ZT) / 2),
                        bevel=0.05), "stone_light")

    # пояс собран вручную, а не cornice(): на фасаде он обязан упереться в портал ворот
    for sx in (-1, 1):
        a.add(p_box((0.22, D + 0.18, BT), loc=(sx * W / 2, 0, BZ), bevel=0.04), "stone_light")
        a.add(p_box((1.99, 0.22, BT), loc=(sx * 1.895, YF, BZ), bevel=0.04), "stone_light")
    a.add(p_box((W + 0.18, 0.22, BT), loc=(0, -YF, BZ), bevel=0.04), "stone_light")

    battlements(a, W, D, ZT, bw=0.44, bh=0.50)

    # Конёк идёт вдоль длинной оси зала, как на референсе: у gable_roof он всегда
    # вдоль Y, и на корпусе 5.6x2.7 скаты разворачивало поперёк — выходил горб.
    # Кровля уже корпуса (4.6 против 5.6) и пологая: конёк поднимается над зубцами
    # на треть метра, по бокам остаётся открытый верх стены — читается как боевой ход.
    zr = gable_roof_x(a, 4.60, 1.90, 2.62, pitch_deg=22.0, ox=0.14, oy=0.16)
    # низ фронтона опущен под верх стены (2.50 < 2.60), иначе в прозорах видна щель
    gable_wall_x(a, 4.60, 1.90, 2.50, zr, depth=0.16)
    chimney(a, -2.10, 0.72, 2.40, h=1.65, w=0.60)

    # ворота по центру фасада + порог: проём начинается от верха цоколя, поэтому
    # без ступени он был бы отрезан от земли
    gate(a, YF, F, w=1.55, h=1.95)
    a.add(p_box((1.85, 0.50, 0.22), loc=(0, YF - 0.37, 0.07), bevel=0.05), "stone_light")

    # хоругви по бокам от ворот: полотно висит на перекладине под поясом,
    # на каждом — скрещённые мечи (по +-35 градусов в плоскости стены)
    for sx in (-1, 1):
        bx = sx * 1.40
        banner(a, (bx, YF - 0.04, 2.15), w=0.76, h=1.05, pole=False)
        for ss in (-1, 1):
            _sword(a, bx + ss * 0.13, YF - 0.08, 1.50, -ss * 35)

    _shield_rack(a, -2.26)
    _spear_rack(a)

    # наковальня на колоде и бочка — двор оружейника справа от ворот
    a.add(p_box((0.34, 0.30, 0.26), loc=(1.30, -1.98, 0.13), bevel=0.03),
          by_normal("wood_pale", "wood_mid", "wood_dark", 0.7))
    a.add(p_box((0.17, 0.17, 0.07), loc=(1.30, -1.98, 0.295), bevel=0.02), "iron_dark")
    a.add(p_box((0.50, 0.22, 0.13), loc=(1.30, -1.98, 0.395), bevel=0.03), "iron_dark")
    barrel(a, (2.85, -2.00, 0.0))

    # бойницы только на боковых стенах: фасад уже занят воротами и хоругвями
    for sx in (-1, 1):
        for y in (-0.55, 0.55):
            arrow_slit(a, (sx * (W / 2 + 0.02), y, 1.65), rot=(0, 0, sx * 90), h=0.66)
