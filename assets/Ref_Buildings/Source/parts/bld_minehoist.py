"""Подъёмник шахты: каменная подпорная стена со штольней, деревянный копёр с барабаном и вагонетка."""
import random
from build_vitaria import p_box, p_cyl, p_ico, by_normal

NAME = "Bld_MineHoist"
TARGET = (4.2, 3.2, 3.9)   # w, d, h в метрах


def build(a):
    # Стена сдвинута к +Y: фасадная сторона (-Y) отдана копру, рельсам и вагонетке,
    # иначе рама наезжает на стену и постройка читается как один плоский блок.
    WW, WD, WH = 3.0, 0.55, 2.0
    YW = 1.125                      # центр стены по Y
    YF = YW - WD / 2                # лицо стены, от него отсчитываются накладные детали
    OW, OH = 1.10, 1.40             # проём штольни: ширина и высота до верха арки

    # ── цоколь: выступает над землёй всего на 5 см, чтобы пол штольни остался проходимым,
    # но низ уходит под 0 и даёт зданию контакт с грунтом
    a.add(p_box((WW + 0.24, WD + 0.25, 0.20), loc=(0, YW - 0.015, -0.05), bevel=0.05), "stone_dark")

    # ── стена собрана из простенков и перемычки, а не одним боксом: булевых операций нет,
    # тёмный проём внутри монолита был бы просто не виден
    stone = by_normal("stone_light", "stone_mid", "stone_dark", 0.8)
    pier_w = (WW - OW) / 2          # 0.95
    for sx in (-1, 1):
        a.add(p_box((pier_w, WD, OH), loc=(sx * (OW + pier_w) / 2, YW, OH / 2), bevel=0.06), stone)
    a.add(p_box((WW, WD, WH - OH), loc=(0, YW, (WH + OH) / 2), bevel=0.06), stone)
    # парапет: перекрывает верх стены на 7 см, иначе на стыке видна щель
    a.add(p_box((WW + 0.16, WD + 0.12, 0.14), loc=(0, YW, WH), bevel=0.04), "stone_light")

    # рустовка по торцам — светлые блоки вразбежку, дают силуэт стены на игровой дистанции
    for sx in (-1, 1):
        for i, z in enumerate((0.22, 0.62, 1.02, 1.42, 1.82)):
            a.add(p_box((0.36 if i % 2 == 0 else 0.26, WD + 0.07, 0.34),
                        loc=(sx * WW / 2, YW, z), bevel=0.04), "stone_light")
    # выпирающие камни на лице: вынос 9 см даёт им собственную тень, плоская стена без них мертва
    for x, z, w, h in ((-1.20, 0.60, 0.40, 0.28), (-0.78, 1.02, 0.34, 0.26), (-1.10, 1.44, 0.44, 0.24),
                       (1.18, 0.74, 0.36, 0.26), (0.92, 1.70, 0.42, 0.24)):
        a.add(p_box((w, 0.20, h), loc=(x, YF + 0.01, z), bevel=0.035), "stone_light")

    # ── штольня: прямоугольный низ плюс полуцилиндр сверху даёт арку без вырезов.
    # Чёрный объём упирается в заднюю плоскость стены, чтобы сзади не было дыры.
    ar = OW / 2
    zsp = OH - ar                   # пята арки
    a.add(p_box((OW, WD - 0.02, zsp), loc=(0, YW, zsp / 2), bevel=0.0), "black")
    a.add(p_cyl(ar, ar, WD - 0.02, 12, loc=(0, YW + WD / 2 - 0.01, zsp), rot=(90, 0, 0)), "black")

    # крепь штольни: две стойки и венец поверх арки, вынесены на лицо стены
    for sx in (-1, 1):
        a.add(p_box((0.16, 0.22, OH + 0.12), loc=(sx * (ar + 0.09), YF - 0.09, (OH + 0.12) / 2), bevel=0.03), "wood_dark")
    a.add(p_box((OW + 0.62, 0.24, 0.22), loc=(0, YF - 0.09, OH + 0.11), bevel=0.035), "wood_dark")

    # ── копёр: вертикальная стойка, передний подкос и раскос назад в стену.
    # Три бруса на сторону читаются как А-образная рама и держат вылет барабана вперёд.
    XL, ZP = 0.85, 2.55
    for sx in (-1, 1):
        a.add(p_box((0.22, 0.22, ZP), loc=(sx * XL, 0.30, ZP / 2), bevel=0.04), "wood_dark")
        a.add(p_box((0.18, 0.18, 1.22), loc=(sx * XL, 0.56, 2.00), rot=(27.5, 0, 0), bevel=0.03), "wood_dark")
        a.add(p_box((0.18, 0.18, 2.60), loc=(sx * XL, -0.075, 1.225), rot=(-17.0, 0, 0), bevel=0.03), "wood_dark")
        # каменная подушка под пятой подкоса: иначе брус выглядит воткнутым в траву
        a.add(p_box((0.34, 0.34, 0.16), loc=(sx * XL, -0.44, 0.02), bevel=0.04), "stone_light")
    # ригель над венцом крепи: ниже он перечёркивал вход и штольня читалась заложенной
    a.add(p_box((1.88, 0.16, 0.16), loc=(0, 0.30, 1.88), bevel=0.03), "wood_dark")
    a.add(p_box((2.30, 0.30, 0.24), loc=(0, 0.33, ZP + 0.12), bevel=0.04), "wood_dark")
    ZB = ZP + 0.24                  # верх головной балки

    # ── барабан лежит НА балке, ось вынесена вперёд на 0.38: сход троса (y=0.08)
    # должен пройти перед балкой, иначе верёвка втыкается в дерево
    YD, ZD = 0.38, ZB + 0.30
    for sx in (-1, 1):
        a.add(p_box((0.15, 0.26, 0.44), loc=(sx * 0.53, 0.34, ZB + 0.22), bevel=0.03), "wood_dark")
    a.add(p_cyl(0.30, 0.30, 0.85, 12, loc=(-0.425, YD, ZD), rot=(0, 90, 0), bevel=0.02), "wood_mid")
    for x0 in (-0.44, 0.36):
        a.add(p_cyl(0.325, 0.325, 0.08, 12, loc=(x0, YD, ZD), rot=(0, 90, 0)), "iron_dark")
    # рукоять на -X и опущена вперёд-вниз: любой кривошип выше оси уходил под свес навеса
    # и с трёхчетвертной камеры кита его просто не было видно
    a.add(p_cyl(0.05, 0.05, 0.30, 8, loc=(-0.40, YD, ZD), rot=(0, -90, 0)), "iron_dark")
    a.add(p_box((0.08, 0.08, 0.30), loc=(-0.66, YD - 0.131, ZD - 0.075), rot=(120, 0, 0), bevel=0.02), "iron_dark")
    a.add(p_cyl(0.05, 0.05, 0.20, 8, loc=(-0.62, YD - 0.261, ZD - 0.150), rot=(0, -90, 0)), "wood_light")

    # ── односкатный навес над барабаном: скат уходит вниз к -Y, чтобы с фасада
    # была видна синяя плоскость, а не торец
    for sx in (-1, 1):
        a.add(p_box((0.14, 0.14, 0.80), loc=(sx * XL, 0.34, ZB + 0.40), bevel=0.025), "wood_dark")
    a.add(p_box((1.94, 1.10, 0.16), loc=(0, YD, 3.68), rot=(20, 0, 0), bevel=0.03), "roof")
    a.add(p_box((1.98, 0.14, 0.26), loc=(0, -0.117, 3.436), rot=(20, 0, 0), bevel=0.03), "roof_dark")

    # ── трос от барабана вниз: сходит с переднего обвода (y = YD - r) и висит
    # перед входом в штольню, где груз перецепляют
    a.add(p_cyl(0.028, 0.028, ZD - 0.63, 8, loc=(0, YD - 0.30, 0.63)), "rope")
    a.add(p_box((0.09, 0.09, 0.22), loc=(0, 0.08, 0.52), bevel=0.02), "iron_dark")
    a.add(p_box((0.07, 0.07, 0.26), loc=(0, -0.012, 0.318), rot=(45, 0, 0), bevel=0.018), "iron_dark")
    a.add(p_box((0.06, 0.06, 0.20), loc=(0, -0.044, 0.306), rot=(-37, 0, 0), bevel=0.015), "iron_dark")

    # ── путь справа: шпалы кладём первыми, рельсы ложатся сверху на их верх (z=0.09)
    XT = 1.755                      # ось колеи
    G = 0.275                       # половина колеи
    for y in (0.70, 0.28, -0.14, -0.56, -0.98, -1.40):
        a.add(p_box((0.78, 0.13, 0.09), loc=(XT, y, 0.045), bevel=0.02), "wood_dark")
    for sx in (-1, 1):
        a.add(p_box((0.07, 2.50, 0.06), loc=(XT + sx * G, -0.47, 0.115), bevel=0.015), "rail")

    # ── вагонетка: открытый кузов из пяти щитов, колёса ровно на рельсах
    YC, ZF = -0.75, 0.33
    wood = by_normal("wood_light", "wood_mid", "wood_dark", 0.7)
    a.add(p_box((0.60, 0.45, 0.07), loc=(XT, YC, ZF + 0.035), bevel=0.02), wood)
    for sx in (-1, 1):
        a.add(p_box((0.06, 0.45, 0.38), loc=(XT + sx * 0.27, YC, ZF + 0.26), bevel=0.02), wood)
        a.add(p_box((0.60, 0.06, 0.38), loc=(XT, YC + sx * 0.195, ZF + 0.26), bevel=0.02), wood)
        a.add(p_cyl(0.03, 0.03, 0.58, 6, loc=(XT - G - 0.02, YC + sx * 0.16, 0.235), rot=(0, 90, 0)), "iron_dark")
        for sy in (-1, 1):
            a.add(p_box((0.07, 0.07, 0.44), loc=(XT + sx * 0.28, YC + sy * 0.20, ZF + 0.24), bevel=0.015), "iron_dark")
            a.add(p_cyl(0.09, 0.09, 0.05, 10, loc=(XT + sx * G - 0.025, YC + sy * 0.16, 0.235),
                        rot=(0, 90, 0)), "iron_dark")
    # руда горкой выше борта — только так видно, что вагонетка гружёная
    for i, (x, y, z, r, col) in enumerate(((-0.14, -0.07, 0.74, 0.13, "ore_rock"),
                                          (0.02, 0.05, 0.78, 0.13, "iron_ore_vein"),
                                          (0.14, -0.05, 0.73, 0.12, "ore_rock"),
                                          (-0.02, -0.13, 0.76, 0.11, "iron_ore_vein"))):
        a.add(p_ico(r, sub=1, loc=(XT + x, YC + y, z), scl=(1, 1, 0.75), jitter=0.28,
                    rng=random.Random(11 + i)), col)

    # ── обломки у входа и кирка: закрывают пустой левый угол и объясняют, чем тут заняты
    rk = by_normal("rock", "rock_dark", "rock_dark", 0.35)
    a.add(p_ico(0.30, sub=2, loc=(-1.80, -0.20, 0.11), scl=(1.15, 1.0, 0.62), jitter=0.28,
                rng=random.Random(3), cut=-0.11), rk)
    a.add(p_ico(0.20, sub=1, loc=(-1.42, -0.72, 0.07), scl=(1.1, 1.0, 0.70), jitter=0.30,
                rng=random.Random(7), cut=-0.07), rk)
    # рассыпанная руда сдвинута из-под крюка: в силуэте она слипалась с ним в одно пятно
    for i, (x, y, r, col) in enumerate(((0.52, 0.56, 0.13, "iron_ore_vein"), (-0.40, 0.48, 0.11, "ore_rock"))):
        a.add(p_ico(r, sub=1, loc=(x, y, r * 0.45), scl=(1.1, 1.0, 0.6), jitter=0.30,
                    rng=random.Random(21 + i)), col)
    # кирка прислонена к стене: низ на земле, верх упирается в лицо кладки
    a.add(p_cyl(0.035, 0.035, 1.10, 6, loc=(-1.15, 0.55, 0.0), rot=(-14.4, 0, 0)), "wood_dark")
    a.add(p_box((0.34, 0.07, 0.08), loc=(-1.15, 0.80, 1.06), bevel=0.02), "iron_dark")
    a.add(p_box((0.20, 0.06, 0.06), loc=(-1.30, 0.79, 1.00), rot=(0, 35, 0), bevel=0.015), "iron_dark")
