"""Квадратный донжон: глухой каменный ствол без кровли, вся сила — в силуэте зубцов."""
from build_vitaria import p_box, p_taper_box, by_normal
from parts.common import stone_base, battlements, arch_door, arrow_slit

NAME = "Bld_Keep"
TARGET = (3.0, 3.0, 5.9)   # w, d, h в метрах

# Ствол слегка конический: у башни этой высоты вертикальные стены читаются как труба,
# уклон в 1.2 градуса даёт вес у основания, но не ломает стыковку поясов.
BW, TW = 2.25, 2.05        # ширина ствола внизу и наверху
Z0, SH = 0.18, 4.86        # база ствола (утоплена в цоколь) и его высота
ZT = Z0 + SH               # верх ствола
MZB, MZH = 4.92, 0.32      # низ и толщина машикульного пояса
PZ = 0.26                  # верх цоколя — на него встаёт порог двери


def _half(z):
    """Полуширина конического ствола на высоте z: по ней сажаются пояса, бойницы и русты."""
    t = min(max((z - Z0) / SH, 0.0), 1.0)
    return (BW - (BW - TW) * t) / 2


def _slit(a, x, y, z, nx, ny, h=0.62):
    """Бойница на нефасадной грани. arrow_slit жёстко смещает тёмный проём в -Y, поэтому
    на боках и в +Y он утонул бы внутри светлой рамки; здесь смещение идёт по нормали грани.
    Размеры повторяют arrow_slit, чтобы все бойницы башни выглядели одинаково."""
    rot = (0, 0, 90) if nx else (0, 0, 0)
    a.add(p_box((0.26, 0.10, h + 0.14), loc=(x + nx * 0.03, y + ny * 0.03, z), rot=rot, bevel=0.025), "stone_light")
    a.add(p_box((0.11, 0.08, h), loc=(x + nx * 0.07, y + ny * 0.07, z), rot=rot, bevel=0.0), "black")


def build(a):
    stone_base(a, 2.72, 2.72, h=PZ)
    a.add(p_taper_box((BW, BW), (TW, TW), SH, loc=(0, 0, Z0), bevel=0.05),
          by_normal("stone_light", "stone_mid", "stone_dark", 0.8))

    # Два тонких пояса дробят глухую стену по высоте. Нижний поднят до 2.25, а не до 1.6:
    # архивольт двери доходит до 1.97, и пояс на 1.6 прошёл бы прямо через портал.
    for z in (2.25, 3.60):
        w = 2 * _half(z) + 0.16
        a.add(p_box((w, w, 0.14), loc=(0, 0, z), bevel=0.035), "stone_light")

    # Русты: блок посажен на само ребро, поэтому выступает сразу на две грани.
    # Цепочка плотная и с чередованием размера — тремя редкими блоками угол читался
    # как случайные шишки, а не как перевязка кладки. Цепь упирается в пояса и там обрывается.
    for sx in (-1, 1):
        for sy in (-1, 1):
            for i in range(12):
                z = 0.46 + 0.32 * i + (0.06 if i >= 6 else 0.0) + (0.12 if i >= 10 else 0.0)
                s = 0.36 if i % 2 == 0 else 0.26
                h = _half(z)
                a.add(p_box((s, s, 0.30), loc=(sx * h, sy * h, z), bevel=0.04), "stone_light")

    # Консоли под машикулями: p_taper_box расширяется кверху, поэтому низ уходит в тень.
    # Верх консоли доведён почти до кромки пояса — иначе свес висит сам по себе,
    # а консоли под ним читаются отдельными шишками (так было на первом рендере).
    hc = _half(MZB - 0.16) + 0.06
    for s in (-1, 1):
        for t in (-0.74, 0.0, 0.74):
            a.add(p_taper_box((0.32, 0.18), (0.32, 0.30), 0.32,
                              loc=(t, s * hc, MZB - 0.32), bevel=0.03), "stone_light")
            a.add(p_taper_box((0.18, 0.32), (0.30, 0.32), 0.32,
                              loc=(s * hc, t, MZB - 0.32), bevel=0.03), "stone_light")

    # Машикульный пояс шире ствола: свес даёт горизонтальный разрыв силуэта перед зубцами.
    # Низ тёмный — иначе выступ теряется, у кита нет теней от света.
    a.add(p_box((2.55, 2.55, MZH), loc=(0, 0, MZB + MZH / 2), bevel=0.05),
          by_normal("stone_light", "stone_light", "stone_dark", 0.6))

    # Верх открытый: пояс служит полом боевой площадки, зубцы стоят прямо на нём.
    # Отсутствие кровли и отличает донжон от круглой башни.
    battlements(a, 2.50, 2.50, MZB + MZH, bw=0.42, bh=0.52, gap=0.20)

    # Фасад — -Y. Дверь ниже поясов, порог стоит на цоколе: с земли к ней две ступени.
    yf = -_half(0.9)
    arch_door(a, yf, PZ, w=0.68, h=1.20)
    a.add(p_box((1.24, 0.46, 0.20), loc=(0, yf - 0.30, 0.07), bevel=0.05), "stone_light")

    # Бойницы: на фасаде две, на остальных гранях по одной в среднем ярусе.
    arrow_slit(a, (0.0, -_half(2.95) - 0.03, 2.95))
    arrow_slit(a, (0.0, -_half(4.14) - 0.03, 4.14))
    _slit(a, 0.0, _half(2.95), 2.95, 0, 1)
    for sx in (-1, 1):
        _slit(a, sx * _half(2.95), 0.0, 2.95, sx, 0)
